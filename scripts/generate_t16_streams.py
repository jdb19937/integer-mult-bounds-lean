#!/usr/bin/env python3
"""Import the selected T16 (PR1094) eight-stream data schedule for the Lean stream check.

usage: generate_t16_streams.py UPSTREAM_CHECKOUT

Reads hash-pinned JSON from the upstream checkout: the selected replay archive's global
template, idle remainder frames and data phases, and the PR1094 owner records. No upstream
code is executed. Axes are written in the orthonormal basis `B_q ⊕ I` of each port: index 0 is
`q`, indices 1..8 the other low basis vectors, and index `j ≥ 9` the coordinate vector `e_j`.
"""
import gzip
import hashlib
import json
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'IntegerMultBounds/Networks/Certificates/T16/Streams'
NS = 'IntegerMultBounds.Networks.Certificates.T16.Streams'
REPLAY = 'research/community-frontier1094-audit/selected-replay.tar.gz'
OWNERS = 'research/complex-t16-rare-pattern-exchanges/data/OWNERS.json.gz'
MEMBERS = {
    'template': 'candidate/strict/global/hosted/GLOBAL-TEMPLATE.json.gz',
    'frames': 'candidate/strict/global/hosted/IDLE-REMAINDER-FRAMES.json.gz',
    'phases': 'candidate/strict/global/base/work/complex-nine-native/DATA-PHASES.json',
}
PINS = {
    REPLAY: None,
    OWNERS: None,
}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def load(src):
    raw = {}
    with tarfile.open(src / REPLAY) as archive:
        for key, name in MEMBERS.items():
            data = archive.extractfile(name).read()
            raw[key] = json.loads(gzip.decompress(data) if name.endswith('.gz') else data)
    owners_bytes = (src / OWNERS).read_bytes()
    raw['owners'] = json.loads(gzip.decompress(owners_bytes))
    digests = {REPLAY: sha((src / REPLAY).read_bytes()), OWNERS: sha(owners_bytes)}
    return raw, digests


def dot(v, w):
    return (v & w).bit_count() & 1


def basis(recipe):
    q = int(recipe['q'])
    low = [q]
    for child in recipe['idle_children']:
        for a in map(int, child['orthogonal_axes']):
            if a < 512 and a not in low:
                low.append(a)
    full = low + [1 << j for j in range(9, 73)]
    assert len(full) == 73, 'basis size'
    for a in full:
        for b in full:
            assert dot(a, b) == (1 if a == b else 0), 'basis not orthonormal'
    return full


def axis_mask(B, axes):
    index = {b: k for k, b in enumerate(B)}
    mask = 0
    for a in axes:
        k = index[int(a)]
        assert not mask >> k & 1, 'repeated axis'
        mask |= 1 << k
    return mask


def coord_mask(B, v):
    return sum(dot(b, v) << k for k, b in enumerate(B))


def lean_bool(b):
    return 'true' if b else 'false'


def header(doc, imports):
    return ('module\n\n' + ''.join(f'public import {NS}.{i}\n' for i in imports)
            + f'\n/-! Generated by scripts/generate_t16_streams.py. {doc} -/\n'
            '@[expose] public section\nnamespace ' + NS + '\n\n')

CHUNK = 7


def check_text(replica):
    """The check of one replica, in kernel chunks of `CHUNK` ports."""
    text = header(f'The kernel check of every port of replica {replica}, {CHUNK} ports at a time.',
                  ['Template', 'Ports', f'Groups{replica}', 'Chunks'])
    test = f'fun gp => groupAccepts template localPair localReverse gp.2 gp.1 {replica}'
    text += f'theorem groups{replica}_length : groups{replica}.length = 112 := by decide\n\n'
    for k in range(112 // CHUNK):
        text += (f'theorem replica{replica}_chunk{k} :\n'
                 f'    (((groups{replica}.zip ports).drop ({CHUNK} * {k})).take {CHUNK}).all\n'
                 f'      ({test}) = true := by\n  decide +kernel\n\n')
    chunks = ', '.join(f'replica{replica}_chunk{k}' for k in range(112 // CHUNK))
    text += (f'theorem replica{replica}_accepts :\n'
             f'    ((groups{replica}.zip ports).all {test}) = true := by\n'
             f'  refine all_of_chunks _ {CHUNK} {112 // CHUNK} _ ?_ fun k hk => ?_\n'
             f'  · rw [List.length_zip, groups{replica}_length]\n'
             f'    exact Nat.min_le_left _ _\n'
             f'  · match k, hk with\n'
             + ''.join(f'    | {k}, _ => exact replica{replica}_chunk{k}\n' for k in range(112 // CHUNK))
             + f'    | _ + {112 // CHUNK}, hk => exact absurd hk (by omega)\n'
             + '\nend ' + NS + '\n')
    return text


def main():
    src = Path(sys.argv[1])
    raw, digests = load(src)
    t, frames, phases, owners = raw['template'], raw['frames'], raw['phases'], raw['owners']
    local = {r['stage']: r for r in t['recipe'] if r['kind'] == 'local'}
    assert sorted(local) == list(range(9))
    # template
    events = []
    for e in t['execution_schedule']:
        k = e['kind']
        if k == 'local_cover_sweep':
            events.append(f'.local {e["stage"]} {e["replica"]}')
        elif k == 'idle_cover_sweep':
            c0, c1 = e['child_indices']
            events.append(f'.idle {e["replica"]} {e["pair"]} {c0} {c1}')
        elif k == 'bridge':
            c = e['coefficient']
            events.append(f'.bridge {e["replica"]} {e["dst"]} {e["src"]} ({c})')
        elif k == 'terminal_Y_translations':
            events.append(f'.terminalY {e["replica"]} {e["pairs"]}')
        elif k == 'terminal':
            events.append(f'.terminal {e["replica"]} {e["pairs"]}')
        elif k == 'bank_padding_cover_sweep':
            assert not t['bank_padding'] or t['bank_padding'] == {} or t['bank_padding'].get('children') in ([], None)
        elif k == 'translate_every_live_family':
            pass
        else:
            raise ValueError(k)
    text = header('The global data template and the local stage recipes.', ['Schedule'])
    text += ('def localPair : ℕ → ℕ\n' + ''.join(f'  | {s} => {local[s]["pair"]}\n' for s in range(9))
             + '  | _ => 0\n\n')
    text += ('def localReverse : ℕ → Bool\n'
             + ''.join(f'  | {s} => {lean_bool(local[s]["reverse"])}\n' for s in range(9)) + '  | _ => false\n\n')
    text += 'def template : List TEvent := [\n  ' + ',\n  '.join(events) + ']\n\nend ' + NS + '\n'
    (OUT / 'Template.lean').write_text(text)
    # ports
    recipes = {r['port']: r for r in phases['recipes']}
    assert sorted(recipes) == list(range(112))
    bases = {}
    lines = []
    for port in range(112):
        r = recipes[port]
        B = basis(r)
        bases[port] = B
        lo = hi = 0
        for k, b in enumerate(B[:9]):
            w = bin(b).count('1') % 4
            lo |= (w & 1) << k
            hi |= (w >> 1) << k
        trans = [coord_mask(B, int(c['translation_after'])) for c in r['idle_children']]
        term = coord_mask(B, int(r['terminal_Y_translation']))
        lines.append(f'  ⟨[{", ".join(map(str, B))}], ({lo}, {hi}), {term}, [{", ".join(map(str, trans))}]⟩')
    text = header('Per-port bases, low weights, terminal translations and idle translations.', ['Schedule'])
    text += 'def ports : List PortData := [\n' + ',\n'.join(lines) + ']\n\nend ' + NS + '\n'
    (OUT / 'Ports.lean').write_text(text)
    # groups
    rows = {}
    for f in frames:
        rows.setdefault((f['replica'], f['port']), []).append(f)
    hosted = {}
    for o in owners:
        port = o['port']
        r = recipes[port]
        axes = r['idle_children'][o['child']]['orthogonal_axes'][o['offset']:o['offset'] + o['width']]
        assert len(axes) == o['width'], 'hosted slice length'
        stream, rem = divmod(o['family'] - o['owner_replica'] * 896, 112)
        assert rem == port and 0 <= stream < 8, 'hosted family mapping'
        slot = o['stage'] * 16 + o['replica']
        hosted.setdefault((o['owner_replica'], port), []).append(
            (slot, stream, axis_mask(bases[port], axes)))
    for replica in range(16):
        text = header(f'Hosted helpers and idle remainder rows of replica {replica}.', ['Schedule'])
        groups = []
        for port in range(112):
            B = bases[port]
            hs = sorted(hosted.get((replica, port), []))
            idle = sorted((f['child'], axis_mask(B, f['orthogonal_axes'])) for f in rows.get((replica, port), []))
            groups.append('  ⟨[' + ', '.join(f'({a}, {b}, {c})' for a, b, c in hs) + '], ['
                          + ', '.join(f'({a}, {b})' for a, b in idle) + ']⟩')
        text += f'def groups{replica} : List GroupData := [\n' + ',\n'.join(groups) + ']\n\nend ' + NS + '\n'
        (OUT / f'Groups{replica}.lean').write_text(text)
    for replica in range(16):
        (OUT / f'Check{replica}.lean').write_text(check_text(replica))
    (OUT / 'streams-provenance.json').write_text(json.dumps(
        {'inputs': digests, 'members': MEMBERS}, indent=2, sort_keys=True) + '\n')


if __name__ == '__main__':
    main()
