#!/usr/bin/env python3
"""Import the pinned PR589 scalar word; generated claims remain kernel-checked.
No source program is executed. Usage: python3 scripts/generate_pr589_scalar.py WORD.gz
Only the first four-gate checkpoint is emitted initially; no full identity claim.
"""
import argparse, gzip, hashlib, json
from pathlib import Path

REVISION = '0fdd7d82de03e43c9e5a1000dfbcd380d1b687d2'
SOURCE = 'research/e8-bit-p111-tuned/tune/bitE8mut-p111-tuned.json.gz'
SHA256 = 'e3e301e62bc2b41dbf1ceac0acf3d35824ebeab1848c5a2142d4577b109da52f'
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'IntegerMultBounds/Networks/Certificates/PR589'
NS = 'IntegerMultBounds.Networks.Certificates.PR589'

def header(imports):
    return 'module\n\n' + ''.join(f'public import {i}\n' for i in imports) + f'\n/-! Generated by scripts/generate_pr589_scalar.py.\nPinned {REVISION}; source {SOURCE}; SHA256 {SHA256}.\nData are untrusted until accompanying kernel proofs are checked. -/\n@[expose] public section\nnamespace {NS}\n'

def row(g):
    f,t,ss=g
    return f'  ⟨{f}, {t}, [{", ".join(map(str,ss))}]⟩'

def array(xs):
    return '#[\n' + ',\n'.join(f'  BitVec.ofNat 661 {x}' for x in xs) + '\n]'

def main():
    ap=argparse.ArgumentParser();ap.add_argument('word',type=Path);a=ap.parse_args()
    raw=a.word.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=SHA256: raise SystemExit('Pinned word hash mismatch')
    w=json.loads(gzip.decompress(raw)); assert (w['v'],w['R'])==(111,439)
    sections={s:w[s] for s in ['D','A','B','C']}
    # Retained helper values are unchanged during the target-only scatter.
    sections['scatter']=[[0,111+t,[w['ret'][k] for k in ks]] for t,ks in enumerate(w['scatter'])]
    OUT.mkdir(parents=True,exist_ok=True)
    for s,gs in sections.items():
        assert all(0<=t<661 and all(0<=x<661 for x in ss) for _,t,ss in gs)
        name='section'+s
        text=header([NS+'.Scalar'])
        names=[]
        for i,(f,t,ss) in enumerate(gs):
            gn=f'{name}Gate{i:04}'
            # Keep every literal below default elaboration recursion limits.
            chunks=[ss[j:j+24] for j in range(0,len(ss),24)]
            expr=' ++ '.join('['+', '.join(map(str,c))+']' for c in chunks) or '[]'
            text+=f'\ndef {gn} : RawGate := ⟨{f}, {t}, {expr}⟩\n'
            names.append(gn)
        cnames=[]
        for i in range(0,len(names),24):
            cn=f'{name}Chunk{i//24:03}'
            text+=f'\ndef {cn} : List RawGate := ['+', '.join(names[i:i+24])+']\n'
            text+=f'theorem {cn}_length : {cn}.length = {len(names[i:i+24])} := by rfl\n'
            cnames.append(cn)
        text+=f'\ndef {name} : List RawGate := '+ ' ++ '.join(cnames)+'\n'
        text+=f'\ntheorem {name}_length : {name}.length = {len(gs)} := by\n  simp only [{name}, List.length_append, '+', '.join(c+'_length' for c in cnames)+']\n'
        text+=f'\nend {NS}\n';(OUT/(s+'.lean')).write_text(text)
    program=sections['D']+sections['A']+sections['scatter']+sections['B']+sections['C']
    state=[1<<i for i in range(661)]
    for _,t,ss in program:
        v=state[t]
        for s in ss:v^=state[s]
        state[t]=v
    assert state==[(1<<i) ^ ((1<<(i-111)) if 111<=i<222 else 0) for i in range(661)]
    # Only this small checkpoint is advertised as a Lean-checked replay so far.
    state=[1<<i for i in range(661)]
    for _,t,ss in sections['D'][:4]:
        for s in ss:state[t]^=state[s]
    text=header([NS+'.D'])
    text+='\ntheorem first_four_bounds : ((sectionD.take 4).all RawGate.bounded) = true := by\n  decide +kernel\n'
    for i in range(111,115):
        text+=f'\ntheorem first_four_row_{i} : replay (sectionD.take 4) initial {i} = BitVec.ofNat 661 {state[i]} := by\n  decide +kernel\n'
    text+='\n/-- Every other symbolic column row is preserved by this prefix. -/\ntheorem first_four_preserves (i : ℕ) (h : i < 111 ∨ 115 ≤ i) :\n    replay (sectionD.take 4) initial i = initial i := by\n  apply replay_preserves\n  intro g hg\n  change g ∈ [sectionDGate0000, sectionDGate0001, sectionDGate0002, sectionDGate0003] at hg\n  simp only [List.mem_cons, List.not_mem_nil, or_false] at hg\n  rcases hg with rfl | rfl | rfl | rfl <;> simp only [sectionDGate0000, sectionDGate0001, sectionDGate0002, sectionDGate0003] <;> omega\n'
    text+=f'\nend {NS}\n';(OUT/'FirstCheckpoint.lean').write_text(text)
    text=header([NS+'.'+s for s in ['D','A','B','C','scatter']])
    text+='\n/-- Literal order, including the retained-helper scatter. Frame zero on scatter\nrecords is only a placeholder: this module asserts scalar semantics only. -/\ndef program : List RawGate := sectionD ++ sectionA ++ sectionscatter ++ sectionB ++ sectionC\n'
    text+='\ntheorem program_length : program.length = 5583 := by\n  simp only [program, List.length_append, sectionD_length, sectionA_length,\n    sectionscatter_length, sectionB_length, sectionC_length]\n'
    text+=f'\nend {NS}\n';(OUT/'Word.lean').write_text(text)
    print('Imported pinned scalar word; Python endpoint checked. Lean certificate covers only first four D gates.')
if __name__=='__main__':main()
