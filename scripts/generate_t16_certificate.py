#!/usr/bin/env python3
"""Deterministically project pinned T16 charges and owner coordinates into Lean.

No supplier code is executed. This imports finite data, not supplier semantics.
Usage: python3 scripts/generate_t16_certificate.py /path/to/integer-mult-bounds
"""
import argparse
from collections import Counter
import gzip
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'IntegerMultBounds/Networks/Certificates/T16'
NS = 'IntegerMultBounds.Networks.Certificates.T16'
REV = '0fdd7d82de03e43c9e5a1000dfbcd380d1b687d2'
PACKAGE = 'research/complex-t16-rare-pattern-exchanges'
LOCAL = 'research/r480-owner-optimum/inputs/local'
PINS = {
    PACKAGE+'/data/PLAN.json': '7bd786ba8e66408f02aa9ef446eaf20c1bfe981ea2e4dd1e5a929f0aa7767bc0',
    PACKAGE+'/data/OWNERS.json.gz': '87902c528dfab7d503dcf8a784260e3ab6fb7424c418a1820f7261f25be7b6bc',
    LOCAL+'/LOCAL-PROGRAMS.json.gz': '241fde27d4e43f5a9cb6b128f9f76c5131a53d09f0371676163f914d0b0fef3a',
    LOCAL+'/CANONICAL-WORD.json.gz': '16bc0ebb04b4be6c0ade74badc6a0c0cdba4215eda86e4ff9f13abf8ecebd219',
}

def header(imports):
    return ('module\n\n'+''.join('public import '+NS+'.'+i+'\n' for i in imports)+
            '\n/-! Generated by scripts/generate_t16_certificate.py; pinned '+REV+
            '. Finite projected data only; no supplier semantics. -/\n@[expose] public section\nnamespace '+NS+'\n\n')

def emit(name, text):
    (OUT/(name+'.lean')).write_text(text+'\nend '+NS+'\n')

def profile(xs):
    c=Counter(xs)
    return '⟨'+','.join(str(c[r]) for r in [1,2,3,4,5,8])+'⟩'

def main():
    if sys.flags.optimize:
        raise SystemExit('Importer schema assertions must remain enabled')
    ap=argparse.ArgumentParser();ap.add_argument('source',type=Path);a=ap.parse_args()
    data={}
    for name,digest in PINS.items():
        raw=(a.source/name).read_bytes()
        if hashlib.sha256(raw).hexdigest()!=digest: raise SystemExit('Pinned hash mismatch: '+name)
        data[name]=json.loads(gzip.decompress(raw) if name.endswith('.gz') else raw)
    plan=data[PACKAGE+'/data/PLAN.json']; owners=data[PACKAGE+'/data/OWNERS.json.gz']
    programs=data[LOCAL+'/LOCAL-PROGRAMS.json.gz']; word=data[LOCAL+'/CANONICAL-WORD.json.gz']
    assert (word['v'],word['R'],len(word['frames']))==(112,480,1004)
    OUT.mkdir(parents=True,exist_ok=True)
    for ori in ['forward','backward']:
        events=programs[ori]; digest=hashlib.sha256(json.dumps(events,separators=(',',':')).encode()).hexdigest()
        assert digest==plan['provider_registry']['gauge44']['orientation_program_sha256'][ori]
        rows=[];ranks=[]
        for i,e in enumerate(events):
            if e[0] not in ('climb','center'): continue
            center=e[0]=='center'
            reg,old,new,rank=(e[1],e[2],e[3],e[4]) if center else (e[2],e[3],e[4],e[5])
            dims=[len(word['frames'][f]) for f in [old,new]]
            assert rank in [1,2,3,4,5,8] and abs(dims[1]-dims[0])==rank
            rows.append('⟨'+','.join(map(str,[i,str(center).lower(),reg,old,new,*dims]))+',.r'+str(rank)+'⟩')
            ranks.append(rank)
        text=header(['Profile'])+f'def {ori}ProgramHash : String := "{digest}"\n\n'
        names=[]
        for j,lo in enumerate(range(0,len(rows),64)):
            name=f'{ori}Charges{j}';names.append(name); rs=rows[lo:lo+64]
            text+=f'def {name} : List Charge := [\n'+',\n'.join(rs)+']\n'
            text+=f'theorem {name}_valid : {name}.all Charge.valid = true := by decide\n'
            text+=f'theorem {name}_profile : chargeProfile {name} = {profile(ranks[lo:lo+64])} := rfl\n\n'
        text+=f'def {ori}Chunks : List (List Charge) := ['+','.join(names)+']\n'
        text+=f'theorem {ori}_profile : chunkProfile {ori}Chunks = {profile(ranks)} := by\n'
        text+='  simp only ['+ori+'Chunks, chunkProfile, '+', '.join(n+'_profile' for n in names)+']\n'
        text+='  rfl\n'
        text+=f'theorem {ori}_cost (price : ℕ → ℕ) : chunkCost {ori}Chunks price =\n'
        text+='    2412*price 1+418*price 2+432*price 3+142*price 4+82*price 5+8*price 8 := by\n'
        text+=f'  rw [chunkCost_eq, {ori}_profile]\n  rfl\n'
        emit(ori.capitalize(),text)
    # Owner projections retain every coordinate and offset; no interval or disjointness claim.
    for part in range(4):
        text=header(['Profile']); subset=owners[part*17280:(part+1)*17280]
        names=[]
        for j,lo in enumerate(range(0,len(subset),64)):
            rs=subset[lo:lo+64];name=f'owners{part}_{j}'
            names.append(name)
            fields=['time','stage','replica','helper','owner_replica','child','port','copy','family','offset','width']
            rows=['⟨'+','.join(str(o[k]) for k in fields)+'⟩' for o in rs]
            text+=f'def {name} : List Owner := [\n'+',\n'.join(rows)+']\n'
            text+=f'theorem {name}_valid : {name}.all Owner.valid = true := by decide\n\n'
            text+=f'theorem {name}_length : {name}.length = {len(rs)} := rfl\n'
        groups=[]
        for g,lo in enumerate(range(0,len(names),30)):
            gn=f'ownerGroup{part}_{g}'; groups.append(gn); ns=names[lo:lo+30]
            text+=f'def {gn} : List (List Owner) := ['+','.join(ns)+']\n'
            text+=f'theorem {gn}_valid : ({gn}.map fun xs => xs.all Owner.valid).all id = true := by\n'
            text+='  simp only ['+gn+', List.map_cons, List.map_nil, '+','.join(n+'_valid' for n in ns)+']\n  rfl\n'
            text+=f'theorem {gn}_length : ({gn}.map List.length).sum = {64*len(ns)} := by\n'
            text+='  simp only ['+gn+', List.map_cons, List.map_nil, '+','.join(n+'_length' for n in ns)+']\n  rfl\n'
        text+=f'def ownerChunks{part} : List (List Owner) := '+' ++ '.join(groups)+'\n'
        text+=f'theorem ownerChunks{part}_valid : (ownerChunks{part}.map fun xs => xs.all Owner.valid).all id = true := by\n'
        text+='  simp only [ownerChunks'+str(part)+', List.map_append, List.all_append, '+','.join(n+'_valid' for n in groups)+']\n  rfl\n'
        text+=f'theorem ownerChunks{part}_length : (ownerChunks{part}.map List.length).sum = 17280 := by\n'
        text+='  simp [ownerChunks'+str(part)+', List.map_append, List.sum_append, '+','.join(n+'_length' for n in groups)+']\n'
        emit('Owners'+str(part),text)
    text=header(['Owners0','Owners1','Owners2','Owners3'])
    text+='def allOwnerChunks := ownerChunks0 ++ ownerChunks1 ++ ownerChunks2 ++ ownerChunks3\n'
    text+='theorem allOwnerChunks_valid : (allOwnerChunks.map fun xs => xs.all Owner.valid).all id = true := by\n'
    text+='  simp only [allOwnerChunks, List.map_append, List.all_append, ownerChunks0_valid, ownerChunks1_valid, ownerChunks2_valid, ownerChunks3_valid]\n  rfl\n'
    text+='theorem allOwnerChunks_length : (allOwnerChunks.map List.length).sum = 69120 := by\n'
    text+='  simp [allOwnerChunks, List.map_append, List.sum_append, ownerChunks0_length, ownerChunks1_length, ownerChunks2_length, ownerChunks3_length]\n'
    emit('Owners',text)
    calls=plan['provider_calls'];assert len(calls)==144
    text=header(['Forward','Backward'])
    callnames=[]
    for k,lo in enumerate(range(0,144,16)):
        name=f'calls{k}';callnames.append(name)
        text+=f'def {name} : List Call := [\n'+',\n'.join('⟨'+str(c['stage'])+','+str(c['replica'])+','+str(c['orientation']=='forward').lower()+'⟩' for c in calls[lo:lo+16])+']\n'
        text+=f'theorem {name}_valid : {name}.all Call.valid = true := by decide\n'
        text+=f'theorem {name}_length : {name}.length = 16 := rfl\n'
    text+='def calls : List Call := '+' ++ '.join(callnames)+'\n'
    text+='theorem calls_valid : calls.all Call.valid = true := by\n  simp [calls, List.all_append, '+','.join(n+'_valid' for n in callnames)+']\n'
    text+='theorem calls_length : calls.length = 144 := by\n  simp [calls, List.length_append, '+','.join(n+'_length' for n in callnames)+']\n'
    text+='def scheduleCost (price : ℕ → ℕ) : ℕ :=\n  (calls.map fun c => if c.forward then chunkCost forwardChunks price else chunkCost backwardChunks price).sum\n'
    text+='theorem scheduleCost_eq (price : ℕ → ℕ) : scheduleCost price =\n'
    text+='    144*(2412*price 1+418*price 2+432*price 3+142*price 4+82*price 5+8*price 8) := by\n'
    text+='  simp only [scheduleCost, forward_cost, backward_cost, ite_self, sum_map_constant, calls_length]\n'
    text+='\n/-- Conditional addition of the selected residual inventory, not a hosting theorem. -/\n'
    text+='theorem selected_profile_cost (price : ℕ → ℕ) :\n'
    text+='    scheduleCost price + (2276*price 1+377*price 3+7*price 7+4866*price 48) =\n'
    text+='    349604*price 1+60192*price 2+62585*price 3+20448*price 4+11808*price 5+7*price 7+1152*price 8+4866*price 48 := by\n'
    text+='  rw [scheduleCost_eq]\n  ring\n'
    emit('Schedule',text)
    # The upstream binder intentionally normalizes timing and gzip reference bytes.
    review=json.loads((a.source/LOCAL/'CLIFFORD-REVIEW.json').read_bytes())
    review.pop('seconds')
    review['canonical_word_sha256']=hashlib.sha256(gzip.decompress((a.source/LOCAL/'CANONICAL-WORD.json.gz').read_bytes())).hexdigest()
    recipes=json.loads((a.source/LOCAL/'CLIFFORD-RECIPES.json').read_bytes())
    review['recipe_sha256']=hashlib.sha256(json.dumps(recipes,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    review_hash=hashlib.sha256(json.dumps(review,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    assert review_hash==plan['provider_registry']['gauge44']['artifact_semantic_sha256']['CLIFFORD-REVIEW.json']
    receipt={'revision':REV,'pinned_files':PINS,'native_charge_projection':3494,
             'owner_rows':69120,'calls':144,'scope':'Finite charge and coordinate projection; no scalar semantics, frame independence, owner-window/disjointness, restoration, precision or price theorem.',
             'clifford_review':'Local receipt bytes differ, but upstream timing/reference normalization matches the selected semantic digest; this is provenance, not a Lean semantic proof.',
             'clifford_review_normalized_sha256':review_hash}
    (OUT/'provenance.json').write_text(json.dumps(receipt,sort_keys=True,indent=2)+'\n')

if __name__=='__main__':main()
