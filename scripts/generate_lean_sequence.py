#!/usr/bin/env python3
"""Generate kernel-checked straight-line composition from existing Runs proofs.

The JSON manifest contains Lean source expressions, not executable Python.
It is an authoring format, not a proof checker: ALWAYS check emitted Lean.
Commands are parameter-free; input-dependent state and cost live in certificates.
"""
import argparse
import json
from pathlib import Path
import re
import sys


def nonempty(value, label):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f'{label} must be a nonempty string')
    return value


def identifier(value, label):
    value = nonempty(value, label)
    if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', value):
        raise ValueError(f'{label} must be a simple Lean identifier')
    return value


def chain(items, join):
    result = items[-1]
    for item in reversed(items[:-1]):
        result = join(item, result)
    return result


def render(manifest):
    if manifest.get('version') != 1:
        raise ValueError('unsupported manifest version')
    namespace = nonempty(manifest.get('namespace'), 'namespace')
    if not all(re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', part) for part in namespace.split('.')):
        raise ValueError('invalid namespace')
    imports = manifest.get('imports')
    cases = manifest.get('cases')
    if not isinstance(imports, list) or not imports or not isinstance(cases, list) or not cases:
        raise ValueError('imports and cases must be nonempty lists')
    lines = ['module', '', 'public import IntegerMultBounds.Schoenhage.CertifiedSequence']
    lines += [f'public import {nonempty(module, "import")}' for module in imports]
    lines += ['', '/-! Generated by scripts/generate_lean_sequence.py; edit the manifest.',
              'Every phase requires an existing proof. Lean checks whole-bank boundaries,',
              'fixed program identity, and all connecting steps. -/', '',
              '@[expose] public section', f'namespace {namespace}',
              'open IntegerMultBounds.Machine IntegerMultBounds.Schoenhage',
              'open IntegerMultBounds.Schoenhage.CertifiedSequence']
    lines += [f'open {nonempty(scope, "open")}' for scope in manifest.get('open', [])]
    lines += ['noncomputable section', '']
    seen = set()
    for case in cases:
        name = identifier(case.get('name'), 'case name')
        if name in seen:
            raise ValueError(f'duplicate case: {name}')
        seen.add(name)
        binders = nonempty(case.get('binders'), 'binders')
        arguments = nonempty(case.get('arguments'), 'arguments')
        start = nonempty(case.get('input'), 'input')
        finish = nonempty(case.get('output'), 'output')
        alphabet, tapes = case.get('alphabet'), case.get('tapes')
        if type(alphabet) is not int or alphabet < 0 or type(tapes) is not int or tapes <= 0:
            raise ValueError('alphabet must be nonnegative and tapes positive integers')
        stages = case.get('stages')
        if not isinstance(stages, list) or not stages:
            raise ValueError(f'{name}: stages must be nonempty')
        commands, blocks = [], []
        for index, stage in enumerate(stages):
            command = nonempty(stage.get('command'), 'command')
            proof = nonempty(stage.get('proof'), 'proof')
            # Inference extracts endpoints and cost from the theorem; no duplicate cost input.
            stage_name = f'{name}Stage{index}'
            lines += [f'def {stage_name} {binders} :=', f'  ofRuns ({proof})', '']
            commands.append(f'({command})')
            blocks.append(f'({stage_name} {arguments})')
        program = chain(commands, lambda first, rest: f'Cmd.seq {first} ({rest})')
        certificate = chain(blocks, lambda first, rest: f'Block.then {first} ({rest})')
        lines += [f'def {name}Program : Cmd {alphabet} {tapes} :=', f'  {program}', '',
                  f'def {name}Certificate {binders} : Block {alphabet} {tapes} ({start}) :=',
                  f'  {certificate}', '',
                  f'def {name}Cost {binders} : ℕ :=',
                  f'  ({name}Certificate {arguments}).bound', '',
                  f'theorem {name}_command {binders} :',
                  f'    ({name}Certificate {arguments}).command = {name}Program := rfl', '',
                  f'theorem {name}_output {binders} :',
                  f'    ({name}Certificate {arguments}).output = ({finish}) := rfl', '',
                  f'theorem {name}_cost {binders} :',
                  f'    {name}Cost {arguments} =',
                  '      ' + ' + '.join(f'{block}.bound' for block in blocks) + f' + {len(stages)-1} := by',
                  f'  simp only [{name}Cost, {name}Certificate, Block.then]', '  omega', '',
                  f'theorem {name}_runs {binders} :',
                  f'    Runs {name}Program ({start}) (· = ({finish})) ({name}Cost {arguments}) :=',
                  f'  ({name}Certificate {arguments}).runs', '',
                  f'theorem {name}_hoare {binders} :',
                  f'    HoareTime (compile (by decide) {name}Program).2',
                  f'      (· = enc ({start})) (· = enc ({finish})) ({name}Cost {arguments}) :=',
                  f'  ({name}Certificate {arguments}).hoare (by decide)', '']
    lines += ['end', f'end {namespace}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('manifest', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--check', action='store_true', help='check reproducibility without writing')
    args = parser.parse_args()
    try:
        result = render(json.loads(args.manifest.read_text()))
        if args.check:
            if not args.output.exists() or args.output.read_text() != result:
                print(f'Generated file is stale: {args.output}', file=sys.stderr)
                return 1
        else:
            args.output.write_text(result)
    except (ValueError, OSError, TypeError, AttributeError) as error:
        parser.error(str(error))
    return 0


if __name__ == '__main__':
    sys.exit(main())
