#!/usr/bin/env python3
"""Import exact PR589 frame IDs; scatter remains a distinct COPY boundary."""
import argparse,gzip,json,hashlib
from pathlib import Path
from generate_pr589_scalar import SHA256
from generate_pr589_full_replay import tree
OUT=Path('IntegerMultBounds/Networks/Certificates/PR589/Frames')
BASE='IntegerMultBounds.Networks.Certificates.PR589'
NS=BASE+'.Frames'
def header(imports):
 return 'module\n\n'+''.join('public import '+i+'\n' for i in imports)+'\n/-! Generated by scripts/generate_pr589_frames.py from pinned PR589 data.\nFrame IDs carry no unproved geometric rank claims. -/\n@[expose] public section\nnamespace '+NS+'\n'
def end():return '\nend '+NS+'\n'
def main():
 ap=argparse.ArgumentParser();ap.add_argument('word',type=Path);a=ap.parse_args()
 data=a.word.read_bytes();assert hashlib.sha256(data).hexdigest()==SHA256
 w=json.loads(gzip.decompress(data));OUT.mkdir(exist_ok=True,parents=True)
 s=header([NS+'.Model'])
 for k,inds in enumerate(w['frames']):s+=f'\ndef label{k:03} : List ℕ := ['+', '.join(map(str,inds))+']\n'
 s+='\ndef labels : ℕ → List ℕ := fun i => '+tree([f'label{k:03}' for k in range(len(w['frames']))])+'\n'
 for name,refs in [('initialRefs',w['start']),('finalRefs',w['final'])]:s+=f'\ndef {name} (i : ℕ) : ℕ := '+tree(refs)+'\n'
 s+='\ndef retained : List ℕ := ['+', '.join(map(str,w['ret']))+']\n'
 for k,line in enumerate(w['lines']):s+=f'\ndef line{k:03} : List ℤ := ['+', '.join(map(str,line))+']\n'
 s+='\ndef lines : ℕ → List ℤ := fun i => '+tree([f'line{k:03}' for k in range(len(w['lines']))])+'\n'
 s+='\ntheorem initial_ids_bounded : ∀ i : Fin 661, initialRefs i.val < 636 := by decide +kernel\n'
 s+='\ntheorem final_ids_bounded : ∀ i : Fin 661, finalRefs i.val < 636 := by decide +kernel\n'
 (OUT/'Data.lean').write_text(s+end())
 refs=w['start'].copy();chunks=[];idx=0
 for sec in ['D','A','scatter','B','C']:
  gs=w[sec]
  if sec=='scatter':
   scatterrefs=refs.copy();idx+=(len(gs)+23)//24;continue
  for offset in range(0,len(gs),24):
   gates=gs[offset:offset+24];before=refs.copy()
   for frame,target,sources in gates:
    for i in [target]+sources:refs[i]=frame
   k=idx;idx+=1;chunk=f'section{sec}Chunk{offset//24:03}';chunks.append((k,sec,chunk))
   s=header([NS+'.Model',BASE+'.Bounds'])
   for prefix,vals in [('before',before),('after',refs)]:s+=f'\ndef {prefix}{k:03} (i : ℕ) : ℕ := '+tree(vals)+'\n'
   s+=f'\ntheorem checked{k:03} : run {chunk} (snapshot before{k:03}) = snapshot after{k:03} := by\n  apply checkpoint _ _ _ (bounded_touched _ bounds{k:03})\n  decide +kernel\n'
   s+=f'\ntheorem frame_ids{k:03} : {chunk}.all (fun g => g.frame < 636) = true := by decide +kernel\n'
   (OUT/f'Chunk{k:03}.lean').write_text(s+end())
 for sec in ['D','A','B','C']:
  ks=[k for k,s,_ in chunks if s==sec]
  s=header([NS+f'.Chunk{k:03}' for k in ks])
  s+=f'\ntheorem checked{sec} : run section{sec} (snapshot before{ks[0]:03}) = snapshot after{ks[-1]:03} := by\n  simp only [section{sec}, run_append]\n'
  for j,k in enumerate(ks):
   if j:s+=f'  have link{k:03} : snapshot after{ks[j-1]:03} = snapshot before{k:03} := rfl\n  rw [link{k:03}]\n'
   s+=f'  rw [checked{k:03}]\n'
  (OUT/f'Section{sec}.lean').write_text(s+end())
 s=header([NS+'.Data']+[NS+'.Section'+sec for sec in ['D','A','B','C']]+[BASE+'.scatter'])
 s+='\ndef beforeScatter : ℕ → ℕ := snapshot after091\n\ndef scatterCopies : List Copy := copies beforeScatter sectionscatter\n'
 s+='\ntheorem initial_link : snapshot initialRefs = snapshot before000 := rfl\n'
 s+='\ntheorem scatter_link : scatterFinish beforeScatter = snapshot before097 := rfl\n'
 s+='\ntheorem before_scatter : run (sectionD ++ sectionA) (snapshot initialRefs) = beforeScatter := by\n  rw [run_append, initial_link, checkedD]\n  have link : snapshot after004 = snapshot before005 := rfl\n  rw [link, checkedA]\n  rfl\n'
 s+='\ntheorem after_scatter : run (sectionB ++ sectionC) (scatterFinish beforeScatter) = snapshot after234 := by\n  rw [run_append, scatter_link, checkedB]\n  have link : snapshot after126 = snapshot before127 := rfl\n  rw [link, checkedC]\n'
 s+='\ntheorem scatter_target_zero : ∀ i : Fin 111, beforeScatter (111+i.val) = 0 := by decide +kernel\n'
 # zero frame ID is 0 in pinned source (assert explicitly, never infer from scalar placeholder)
 assert w['frames'][0]==[] and all(scatterrefs[111+i]==0 for i in range(111))
 s+='\ntheorem retained_frames : retained.map beforeScatter = ['+', '.join(str(scatterrefs[i]) for i in w['ret'])+'] := by decide +kernel\n'
 s+='\ntheorem scatter_copy_count : scatterCopies.length = 527 := by decide +kernel\n'
 s+='\ntheorem scatter_register_roles : scatterCopies.all (fun c => decide (111 ≤ c.target ∧ c.target < 222 ∧ 222 ≤ c.source ∧ c.source < 661)) = true := by decide +kernel\n'
 s+='\ntheorem scatter_distinct_frames : scatterCopies.all (fun c => decide (c.targetFrame = 0 ∧ 510 ≤ c.sourceFrame ∧ c.sourceFrame ≤ 518)) = true := by decide +kernel\n'
 s+='\ndef finalUpdates : List (ℕ × ℕ) := (List.range 661).map fun i => (i, finalRefs i)\n\ndef finalEdges : List (ℕ × ℕ) := RankTrace.edges (snapshot after234) finalUpdates\n'
 s+='\ntheorem final_alignment : RankTrace.finish (snapshot after234) finalUpdates = snapshot finalRefs := by\n  funext i\n  rw [finalUpdates, RankTrace.finish_align]\n  by_cases hi : i < 661\n  · simp [List.mem_range, snapshot, hi]\n  · simp [List.mem_range, snapshot, hi]\n'
 (OUT/'Replay.lean').write_text(s+end())
 print(f'Generated data, {len(chunks)} frame checkpoints, four phase assemblies and separate scatter boundary.')
if __name__=='__main__':main()
