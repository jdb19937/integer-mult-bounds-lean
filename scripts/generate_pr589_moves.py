#!/usr/bin/env python3
"""Certify the local MOVE profile of the selected PR589 word.

Every phase incidence of `Frames.edges` is checked as a nested frame pair
(`Geometry.Moves.CheckedPair`), so its `moveRank` is the certified dimension
difference `Geometry.Moves.value`. Values are recomputed here only to state the
per-chunk lists; Lean's kernel checks each list against the frame replay and the
certified dimensions.
"""
import argparse, gzip, hashlib, json
from fractions import Fraction
from pathlib import Path

SHA256 = 'e3e301e62bc2b41dbf1ceac0acf3d35824ebeab1848c5a2142d4577b109da52f'
OUT = Path('IntegerMultBounds/Networks/Certificates/PR589/Geometry/Moves')
BASE = 'IntegerMultBounds.Networks.Certificates.PR589'
NS = BASE + '.Geometry.Moves'
CHUNK = 24


def header(imports, doc):
    return ('module\n\n' + ''.join(f'public import {i}\n' for i in imports) +
            f'\n/-! {doc}\nGenerated by scripts/generate_pr589_moves.py from pinned PR589 data. -/\n'
            f'@[expose] public section\nnamespace {NS}\n')


def end():
    return f'\nend {NS}\n'


def rank(lines, idx):
    rows = [[Fraction(x) for x in lines[i]] for i in idx]
    r = 0
    for c in range(8):
        piv = next((i for i in range(r, len(rows)) if rows[i][c] != 0), None)
        if piv is None:
            continue
        rows[r], rows[piv] = rows[piv], rows[r]
        for i in range(len(rows)):
            if i != r and rows[i][c] != 0:
                f = rows[i][c] / rows[r][c]
                rows[i] = [a - f * b for a, b in zip(rows[i], rows[r])]
        r += 1
    return r


def lean_list(xs):
    return '[' + ', '.join(map(str, xs)) + ']'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('word', type=Path)
    a = ap.parse_args()
    data = a.word.read_bytes()
    assert hashlib.sha256(data).hexdigest() == SHA256
    w = json.loads(gzip.decompress(data))
    dims = [rank(w['lines'], f) for f in w['frames']]
    labels = [set(f) for f in w['frames']]
    OUT.mkdir(parents=True, exist_ok=True)

    def value(p):
        x, y = p
        assert x == y or labels[x] <= labels[y] or labels[y] <= labels[x]
        return abs(dims[y] - dims[x])

    refs = w['start'].copy()
    idx = 0
    sections = {}
    allvalues = []
    for sec in ['D', 'A', 'scatter', 'B', 'C']:
        gs = w[sec]
        if sec == 'scatter':
            idx += (len(gs) + CHUNK - 1) // CHUNK
            continue
        ks = []
        for offset in range(0, len(gs), CHUNK):
            k = idx
            idx += 1
            chunk = f'section{sec}Chunk{offset // CHUNK:03}'
            vals = []
            for frame, target, sources in gs[offset:offset + CHUNK]:
                for i in [target] + sources:
                    vals.append(value((refs[i], frame)))
                    refs[i] = frame
            allvalues += vals
            ks.append((k, chunk))
            edges = f'Frames.edges {chunk} (Frames.snapshot Frames.before{k:03})'
            s = header([f'{BASE}.Frames.Chunk{k:03}', f'{NS}.Model'],
                       f'Checked MOVE ranks of `{chunk}`.')
            s += f'\ndef values{k:03} : List ℕ := {lean_list(vals)}\n'
            s += (f'\ntheorem chunk{k:03} : (∀ p ∈ {edges}, CheckedPair p) ∧\n'
                  f'    ({edges}).map value = values{k:03} := by\n  decide +kernel\n')
            (OUT / f'Chunk{k:03}.lean').write_text(s + end())
        sections[sec] = ks

    for sec, ks in sections.items():
        k0 = ks[0][0]
        start = f'(Frames.snapshot Frames.before{k0:03})'
        parts = [f'Frames.edges {c} (Frames.snapshot Frames.before{k:03})' for k, c in ks]
        s = header([f'{NS}.Chunk{k:03}' for k, _ in ks] + [f'{BASE}.Frames.Section{sec}'],
                   f'Checked MOVE ranks of section {sec}.')
        s += f'\ndef values{sec} : List ℕ := ' + ' ++ '.join(f'values{k:03}' for k, _ in ks) + '\n'
        s += f'\ntheorem edges{sec}_eq : Frames.edges section{sec} {start} =\n    ' + ' ++\n    '.join(parts) + ' := by\n'
        s += f'  simp only [section{sec}, Frames.edges_append, Frames.run_append]\n'
        for j, (k, _) in enumerate(ks[:-1]):
            k1 = ks[j + 1][0]
            s += (f'  rw [Frames.checked{k:03}, show Frames.snapshot Frames.after{k:03} = '
                  f'Frames.snapshot Frames.before{k1:03} from rfl]\n')
        s += f'\ntheorem checked{sec} : ∀ p ∈ Frames.edges section{sec} {start}, CheckedPair p := by\n'
        s += f'  rw [edges{sec}_eq]\n  simp only [List.forall_mem_append]\n'
        term = f'chunk{ks[0][0]:03}.1'
        for k, _ in ks[1:]:
            term = f'⟨{term}, chunk{k:03}.1⟩'
        s += f'  exact {term}\n'
        s += (f'\ntheorem values{sec}_eq : (Frames.edges section{sec} {start}).map value = values{sec} := by\n'
              f'  rw [edges{sec}_eq]\n  simp only [List.map_append, ' +
              ', '.join(f'chunk{k:03}.2' for k, _ in ks) + f', values{sec}]\n')
        (OUT / f'Section{sec}.lean').write_text(s + end())

    phase = [v for v in allvalues]
    hist = [phase.count(r) for r in range(9)]
    paid = [v for v in phase if v != 0] + [7] * 9
    paid_hist = [paid.count(r) for r in range(9)]

    s = header([f'{NS}.Section{sec}' for sec in ['D', 'A', 'B', 'C']] +
               [f'{BASE}.Frames.Replay', f'{BASE}.Geometry.CopyRanks'],
               'The local MOVE profile of the selected PR589 word: every phase and final-alignment\n'
               'incidence is a nested frame pair, its rank is the certified dimension difference,\n'
               'and the positive ranks with the nine COPY ranks give the upstream local histogram.')
    s += ('\n/-- Every phase incidence in execution order: D and A from the initial frames, then B and C\n'
          'from the scatter boundary. Scatter itself is the separate COPY boundary. -/\n'
          'def phaseEdges : List (ℕ × ℕ) :=\n'
          '  Frames.edges (sectionD ++ sectionA) (Frames.snapshot Frames.initialRefs) ++\n'
          '    Frames.edges (sectionB ++ sectionC) (Frames.scatterFinish Frames.beforeScatter)\n')
    s += '\ndef phaseValues : List ℕ := valuesD ++ valuesA ++ valuesB ++ valuesC\n'
    dA, dB, dC = sections['A'][0][0], sections['B'][0][0], sections['C'][0][0]
    lD, lB = sections['D'][-1][0], sections['B'][-1][0]
    s += ('\ntheorem phaseEdges_eq : phaseEdges =\n'
          f'    Frames.edges sectionD (Frames.snapshot Frames.before{sections["D"][0][0]:03}) ++\n'
          f'      Frames.edges sectionA (Frames.snapshot Frames.before{dA:03}) ++\n'
          f'    (Frames.edges sectionB (Frames.snapshot Frames.before{dB:03}) ++\n'
          f'      Frames.edges sectionC (Frames.snapshot Frames.before{dC:03})) := by\n'
          '  rw [phaseEdges, Frames.edges_append, Frames.edges_append, Frames.initial_link, Frames.scatter_link,\n'
          f'    Frames.checkedD, Frames.checkedB,\n'
          f'    show Frames.snapshot Frames.after{lD:03} = Frames.snapshot Frames.before{dA:03} from rfl,\n'
          f'    show Frames.snapshot Frames.after{lB:03} = Frames.snapshot Frames.before{dC:03} from rfl]\n')
    s += ('\ntheorem phase_checked : ∀ p ∈ phaseEdges, CheckedPair p := by\n'
          '  rw [phaseEdges_eq]\n  simp only [List.forall_mem_append]\n'
          '  exact ⟨⟨checkedD, checkedA⟩, checkedB, checkedC⟩\n')
    s += ('\ntheorem phase_values : phaseEdges.map value = phaseValues := by\n'
          '  rw [phaseEdges_eq]\n'
          '  simp only [List.map_append, valuesD_eq, valuesA_eq, valuesB_eq, valuesC_eq, phaseValues,\n'
          '    List.append_assoc]\n')
    s += ('\n/-- The rank of every phase incidence is the certified dimension difference. -/\n'
          'theorem phase_ranks : phaseEdges.map (fun p => moveRank p.1 p.2) = phaseValues :=\n'
          '  (profile _ phase_checked).trans phase_values\n')
    s += (f'\ntheorem phase_length : phaseValues.length = {len(phase)} := by decide +kernel\n'
          f'\ntheorem phase_histogram : (List.range 9).map phaseValues.count = {lean_list(hist)} := by\n'
          '  decide +kernel\n')
    s += ('\ntheorem final_checked : (∀ p ∈ Frames.finalEdges, CheckedPair p) ∧\n'
          '    Frames.finalEdges.map value = List.replicate 661 0 := by\n  decide +kernel\n')
    s += ('\n/-- Final alignment pays no rank: every final incidence has rank zero. -/\n'
          'theorem final_ranks : Frames.finalEdges.map (fun p => moveRank p.1 p.2) = List.replicate 661 0 :=\n'
          '  (profile _ final_checked.1).trans final_checked.2\n')
    s += ('\n/-- The ranks of the nine retained COPY operators. -/\n'
          'noncomputable def copyRanks : List ℕ :=\n'
          f'  {lean_list(range(510, 519))}.map fun i => Module.finrank ℚ (LinearMap.range (-projector i))\n')
    s += ('\ntheorem copyRanks_eq : copyRanks = List.replicate 9 7 := by\n'
          '  simp only [copyRanks, List.map_cons, List.map_nil, ' +
          ', '.join(f'copy_rank{i}' for i in range(510, 519)) + ']\n  rfl\n')
    s += ('\n/-- The local paid profile: the positive MOVE ranks of the phase incidences, then the nine\n'
          'COPY ranks. -/\n'
          'noncomputable def localPaid : List ℕ :=\n'
          '  (phaseEdges.map fun p => moveRank p.1 p.2).filter (· ≠ 0) ++ copyRanks\n')
    s += ('\n/-- The local paid histogram `{1:1323, 2:1342, 3:79, 4:44, 5:102, 6:11, 7:19}`, as recorded in\n'
          'the selected tuned word\'s `EXPECTED.json` (`word.local_histogram`). -/\n'
          f'theorem localPaid_histogram : (List.range 9).map localPaid.count = {lean_list(paid_hist)} := by\n'
          '  rw [localPaid, phase_ranks, copyRanks_eq]\n  decide +kernel\n')
    (OUT / 'Profile.lean').write_text(s + end())
    print('chunks', sum(len(v) for v in sections.values()), 'phase', len(phase), 'hist', hist, 'paid', paid_hist)


if __name__ == '__main__':
    main()
