#!/usr/bin/env python3
"""Import the selected T16 (PR1094) helper role assignment for the Lean invocation programs.

usage: generate_t16_roles.py UPSTREAM_CHECKOUT

Reads the hash-pinned PR1094 owner records and writes, for every stage and replica, the
physical family hosted by each of the 480 helper registers of that local invocation. No
upstream code is executed. Every consequence used by the proofs (distinct registers, hosted
slices, widths) is checked in Lean.
"""
import gzip
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'IntegerMultBounds/Networks/Certificates/T16/Impl'
NS = 'IntegerMultBounds.Networks.Certificates.T16.Impl'
OWNERS = 'research/complex-t16-rare-pattern-exchanges/data/OWNERS.json.gz'
OWNERS_SHA = '87902c528dfab7d503dcf8a784260e3ab6fb7424c418a1820f7261f25be7b6bc'


def main():
    src = Path(sys.argv[1])
    raw = (src / OWNERS).read_bytes()
    if hashlib.sha256(raw).hexdigest() != OWNERS_SHA:
        raise SystemExit('pinned hash mismatch: ' + OWNERS)
    owners = json.loads(gzip.decompress(raw))
    table = {}
    for o in owners:
        key = (o['stage'], o['replica'])
        table.setdefault(key, {})
        assert o['helper'] not in table[key], 'duplicate helper'
        table[key][o['helper']] = o['family']
    assert sorted(table) == [(s, r) for s in range(9) for r in range(16)], 'complete calls'
    for s in range(9):
        defs = []
        for r in range(16):
            fam = table[s, r]
            assert sorted(fam) == list(range(480)), 'complete helpers'
            defs.append(f'def roles{s}_{r} : List ℕ := [' + ', '.join(str(fam[h]) for h in range(480)) + ']\n')
        body = '\n'.join(defs)
        body += (f'\ndef roles{s} : ℕ → List ℕ\n'
                 + ''.join(f'  | {r} => roles{s}_{r}\n' for r in range(16)) + '  | _ => []\n')
        text = ('module\n\npublic import IntegerMultBounds.Networks.Certificates.T16.Streams.Schedule\n\n'
                f'/-! Generated by scripts/generate_t16_roles.py. The family of every helper register of'
                f' the stage-{s} invocations, by replica. -/\n'
                '@[expose] public section\nnamespace ' + NS + '\n\n' + body + '\nend ' + NS + '\n')
        (OUT / f'Roles{s}.lean').write_text(text)
    imports = ''.join(f'public import {NS}.Roles{s}\n' for s in range(9))
    text = ('module\n\n' + imports +
            '\n/-! Generated by scripts/generate_t16_roles.py. Helper families of every local'
            ' invocation. -/\n@[expose] public section\nnamespace ' + NS + '\n\n'
            '/-- The helper families of the invocation at stage `s`, replica `r`, in register order. -/\n'
            'def rolesList (s r : ℕ) : List ℕ :=\n  (match s with\n'
            + ''.join(f'    | {s} => roles{s}\n' for s in range(9)) +
            '    | _ => fun _ => []) r\n\n'
            '/-- The family of helper register `h` of the invocation at stage `s`, replica `r`. -/\n'
            'def helperFamily (s r h : ℕ) : ℕ := (rolesList s r).getD h 0\n\nend ' + NS + '\n')
    (OUT / 'Roles.lean').write_text(text)
    (OUT / 'roles-provenance.json').write_text(json.dumps({'inputs': {OWNERS: OWNERS_SHA}}, indent=2) + '\n')


if __name__ == '__main__':
    main()
