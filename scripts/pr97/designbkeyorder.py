"""Emit inverse-position checks for the concrete design-B ordering keys."""
import hashlib
import json
from pathlib import Path

import designbword
import stage2designb


def emit(result, compiled, destination):
    assert result['source']['upstream'] == stage2designb.UPSTREAM
    assert result['source']['sha256'] == stage2designb.PINS
    slot = dict(compiled['slotMap'])
    sigma = {slot[s]: tuple(f) for s, f in enumerate(result['sigma'])}
    keys = [sorted(compiled['deferred'], key=lambda s: sigma[s] != (0, 0)),
            compiled['deferred'], compiled['earlySources'], compiled['lateSources']]
    for key in keys:
        assert len(set(key)) == len(key)
        assert all(0 <= s < 32768 for s in key)
    inverse = [[0] * 4 for _ in range(32768)]
    for k, key in enumerate(keys):
        for i, s in enumerate(key):
            inverse[s][k] = i
    digest = hashlib.sha256(json.dumps(keys, separators=(',', ':')).encode()).hexdigest()
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Local'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Local'
    opening = (f'/-! Generated by scripts/pr97/designbkeyorder.py from upstream {stage2designb.UPSTREAM}.\n'
               f'Pinned input hashes {json.dumps(stage2designb.PINS, sort_keys=True)}.\n'
               f'Canonical ordering-key SHA-256 {digest}.\n'
               'Inverse positions are untrusted until checked against the existing key lists. -/\n'
               f'@[expose] public section\nnamespace {prefix}.KeyOrderB\nnoncomputable section\n')

    def write(name, imports, body):
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('module\n\n' + '\n'.join('public import ' + m for m in imports)
                        + '\n\n' + opening + '\n\n'.join(body) + f'\nend\nend {prefix}.KeyOrderB\n')

    imports, parts = [], []
    for k in range(8):
        name = f'Inverse{k:02d}'
        imports.append(prefix + '.DataKeyB.' + name)
        body, chunks = [], []
        for j in range(32):
            chunk = f'inverse{k:02d}_{j:02d}'
            chunks.append(chunk)
            vals = [f'({a}, {b}, {c}, {d})' for a, b, c, d in inverse[4096*k+128*j:4096*k+128*(j+1)]]
            body.append(f'def {chunk} : Tree (Nat × Nat × Nat × Nat) := ' + designbword.tree_text(vals))
        part = f'inverse{k:02d}'
        parts.append(part)
        body.append(f'def {part} : Tree (Nat × Nat × Nat × Nat) := ' + designbword.top(chunks))
        write(f'DataKeyB/{name}.lean', [prefix + '.Kernel'], body)
    write('DataKeyB/Inverse.lean', imports + [prefix + '.UseSlotsB', prefix + '.KeyIndexB',
          'IntegerMultBounds.MathlibTM2.M8.Frames.AssignmentB.Data'], [
        'def inverse : Tree (Nat × Nat × Nat × Nat) := ' + designbword.top(parts),
        'def readoutIndex (s : Nat) : Nat := (inverse.get 32768 s).1',
        'def deferredIndex (s : Nat) : Nat := (inverse.get 32768 s).2.1',
        'def earlyIndex (s : Nat) : Nat := (inverse.get 32768 s).2.2.1',
        'def lateIndex (s : Nat) : Nat := (inverse.get 32768 s).2.2.2',
    ])
    groups = []
    groups.append(('readout', 'readoutIndex', 'Frames.AssignmentB.readoutOrder', [
        (f'Frames.AssignmentB.readoutOrder{i:03d}', j, min(128, len(keys[0])-j))
        for i, j in enumerate(range(0, len(keys[0]), 128))], []))
    deferred = []
    for k, start in enumerate(range(0, len(keys[1]), designbword.DCHUNK)):
        for j, offset in enumerate(range(0, min(designbword.DCHUNK, len(keys[1])-start), 128)):
            deferred.append((f'deferred{k}_{j:02d}', start+offset,
                             min(128, designbword.DCHUNK-offset, len(keys[1])-start-offset)))
    groups.append(('deferred', 'deferredIndex', 'deferredUses', deferred,
                   [f'deferred{k}' for k in range((len(keys[1])+2999)//3000)]))
    for pos, phase in [(2, 'early'), (3, 'late')]:
        groups.append((phase, phase+'Index', phase+'V', [
            (f'{phase}V_{i:02d}', j, min(128, len(keys[pos])-j))
            for i, j in enumerate(range(0, len(keys[pos]), 128))], []))
    all_imports, totals = [], []
    for phase, index, full, chunks, unfold in groups:
        facts, lengths = [], []
        mapped = phase != 'readout'
        for k in range((len(chunks)+7)//8):
            name = f'{phase.title()}{k:02d}'
            all_imports.append(prefix + '.ChecksKeyB.' + name)
            body = []
            for j in range(8*k, min(8*(k+1), len(chunks))):
                chunk, start, size = chunks[j]
                expr = f'({chunk}.map useSlotB)' if mapped else chunk
                fact = f'{phase}{j:03d}_indexed'
                length = f'{phase}{j:03d}_length'
                facts.append(fact)
                if j < len(chunks) - 1:
                    lengths.append(length)
                    body.append(f'theorem {length} : {chunk}.length = {size} := by\n  decide +kernel')
                body += [f'theorem {fact} : indexCheck {index} {start} {expr} = true := by\n  decide +kernel']
            write(f'ChecksKeyB/{name}.lean', [prefix + '.DataKeyB.Inverse'], body)
        expr = f'({full}.map useSlotB)' if mapped else full
        totals.append(f'theorem {phase}_indexed : indexCheck {index} 0 {expr} = true := by\n'
                      '  simp only [' + ', '.join([full, *unfold, *(['List.map_append'] if mapped else []), 'indexCheck_append',
                          *(['List.length_map'] if mapped else []), 'List.length_append', *lengths, 'Nat.reduceAdd', *facts, 'Bool.true_and']) + ']')
        totals.append(f'theorem {phase}_nodup : {expr}.Nodup := nodup_of_indexCheck {index} _ {phase}_indexed')
    write('KeyOrderChecksB.lean', all_imports, totals)
    emit_readout_sequence(write, prefix, groups, keys, sigma)
    emit_readout_coverage(write, prefix)
    print('key inverse checks:', ', '.join(str(len(k)) for k in keys), 'entries; SHA-256', digest)


def emit_readout_sequence(write, prefix, groups, keys, sigma):
    readouts = groups[0][3]
    deferred = groups[1][3]
    refs = [f'.leaf Frames.AssignmentB.readoutOrder{i:03d}' for i in range(len(readouts))]
    refs += ['.leaf []'] * (128-len(refs))
    write('DataKeyB/ReadoutSequence.lean', [prefix + '.DataKeyB.Inverse', prefix + '.SequenceCheckB'], [
        'def readoutChunks : Tree (List Nat) := ' + designbword.top(refs),
        'def readoutAt (i : Nat) : Nat := ((readoutChunks.get 128 (i / 128))[i % 128]?).getD 0',
        'def zeroReadout (s : Nat) : Bool := decide (Frames.AssignmentB.sigmaLabel s = Frames.Signed.Frame.zero)',
        'def slotInRange (s : Nat) : Bool := Nat.blt s 28866',
        'def zeroKeys : List Nat := (deferredUses.map useSlotB).filter zeroReadout',
        'def nonzeroKeys : List Nat := (deferredUses.map useSlotB).filter fun s => !zeroReadout s',
    ])
    imports, facts, bounds = [], [], []
    for k in range((len(readouts)+7)//8):
        name = f'ReadoutSequence{k:02d}'
        imports.append(prefix + '.ChecksKeyB.' + name)
        body = []
        for j in range(8*k, min(8*(k+1), len(readouts))):
            chunk, start, size = readouts[j]
            fact = f'readout_sequence{j:03d}'
            facts.append(fact)
            bound = f'readout_sequence{j:03d}_bounded'
            bounds.append(bound)
            body.append(f'theorem {bound} : {chunk}.all slotInRange = true := by\n  decide +kernel')
            body.append(f'theorem {fact} : sequenceCheck readoutAt {start} {chunk} = true := by\n  decide +kernel')
        write(f'ChecksKeyB/{name}.lean', [prefix + '.DataKeyB.ReadoutSequence'], body)
    totals = ['theorem readout_bounded : Frames.AssignmentB.readoutOrder.all slotInRange = true := by\n'
              '  simp only [Frames.AssignmentB.readoutOrder, List.all_append, '
              + ', '.join(bounds) + ', Bool.true_and]']
    last, _, size = readouts[-1]
    totals.append(f'theorem readout_final_length : {last}.length = {size} := by\n  decide +kernel')
    read_lengths = [f'readout{j:03d}_length' for j in range(len(readouts)-1)] + ['readout_final_length']
    totals.append('theorem readout_sequence : sequenceCheck readoutAt 0 Frames.AssignmentB.readoutOrder = true := by\n'
                  '  simp only [Frames.AssignmentB.readoutOrder, sequenceCheck_append, List.length_append, '
                  + ', '.join(read_lengths[:-1] + ['Nat.reduceAdd'] + facts + ['Bool.true_and']) + ']')
    totals.append(f'theorem readout_length : Frames.AssignmentB.readoutOrder.length = {len(keys[0])} := by\n'
                  '  simp only [Frames.AssignmentB.readoutOrder, List.length_append, '
                  + ', '.join(read_lengths + ['Nat.reduceAdd']) + ']')
    zero_total = sum(sigma[s] == (0, 0) for s in keys[1])
    zero_start, other_start = 0, zero_total
    lengths = {'zero': [], 'nonzero': []}
    checks = {'zero': [], 'nonzero': []}
    for k in range((len(deferred)+7)//8):
        name = f'Partition{k:02d}'
        imports.append(prefix + '.ChecksKeyB.' + name)
        body = []
        for j in range(8*k, min(8*(k+1), len(deferred))):
            chunk, start, size = deferred[j]
            zero_count = sum(sigma[s] == (0, 0) for s in keys[1][start:start+size])
            for phase, count, offset, pred in [('zero', zero_count, zero_start, 'zeroReadout'),
                ('nonzero', size-zero_count, other_start, '(fun s => !zeroReadout s)')]:
                expr = f'(({chunk}.map useSlotB).filter {pred})'
                length = f'{phase}{j:03d}_length'
                check = f'{phase}{j:03d}_sequence'
                lengths[phase].append(length)
                checks[phase].append(check)
                body += [f'theorem {length} : {expr}.length = {count} := by\n  decide +kernel',
                         f'theorem {check} : sequenceCheck readoutAt {offset} {expr} = true := by\n  decide +kernel']
            zero_start += zero_count
            other_start += size-zero_count
        write(f'ChecksKeyB/{name}.lean', [prefix + '.DataKeyB.ReadoutSequence'], body)
    assert zero_start == zero_total and other_start == len(keys[0])
    expansions = ['deferredUses'] + groups[1][4] + ['List.map_append', 'List.filter_append', 'List.length_append']
    for phase, offset, count in [('zero', 0, zero_total), ('nonzero', zero_total, len(keys[1])-zero_total)]:
        full = phase + 'Keys'
        totals.append(f'theorem {phase}_sequence : sequenceCheck readoutAt {offset} {full} = true := by\n'
                      '  simp only [' + ', '.join([full, *expansions, 'sequenceCheck_append',
                          *lengths[phase][:-1], 'Nat.reduceAdd', *checks[phase], 'Bool.true_and']) + ']')
        totals.append(f'theorem {phase}_length : {full}.length = {count} := by\n'
                      '  simp only [' + ', '.join([full, *expansions, *lengths[phase], 'Nat.reduceAdd']) + ']')
    totals += [
        'theorem partition_sequence : sequenceCheck readoutAt 0 (zeroKeys ++ nonzeroKeys) = true := by\n'
        '  rw [sequenceCheck_append, zero_length, zero_sequence, nonzero_sequence]\n  rfl',
        'theorem readout_partition : Frames.AssignmentB.readoutOrder = zeroKeys ++ nonzeroKeys := by\n'
        '  apply sequenceCheck_eq readoutAt _ _ _ readout_sequence partition_sequence\n'
        '  simp only [readout_length, List.length_append, zero_length, nonzero_length]',
        'theorem readout_perm_deferred : Frames.AssignmentB.readoutOrder.Perm (deferredUses.map useSlotB) := by\n'
        '  rw [readout_partition]\n  exact List.filter_append_perm zeroReadout _',
    ]
    write('ReadoutOrderChecksB.lean', imports + [prefix + '.KeyOrderChecksB'], totals)
    print('readout stable partition:', zero_total, 'zero frames,', len(keys[0])-zero_total, 'nonzero frames')


def emit_readout_coverage(write, prefix):
    """Check nonzero-frame coverage and the shape of the existing sigma tree."""
    def conjunction(items):
        if len(items) == 1:
            return items[0]
        mid = len(items)//2
        return f'({conjunction(items[:mid])} && {conjunction(items[mid:])})'

    def perfect(items):
        if len(items) == 1:
            return items[0]
        mid = len(items)//2
        return f'⟨by decide, by decide, {perfect(items[:mid])}, {perfect(items[mid:])}⟩'

    imports, coverage, shapes = [], [], []
    for k in range(8):
        name = f'Coverage{k:02d}'
        imports.append(prefix + '.ChecksKeyB.' + name)
        body, facts, parts = [], [], []
        for j in range(64):
            chunk = f'Frames.AssignmentB.sigma{k:02d}_{j:02d}'
            fact = f'coverage{k:02d}_{j:02d}'
            shape = f'sigma{k:02d}_{j:02d}_perfect'
            facts.append(fact)
            parts.append(shape)
            body += [f'theorem {shape} : {chunk}.Perfect 64 :=\n'
                     f'  Tree.perfect_of_perfectB {chunk} 64 (by decide +kernel)',
                     f'theorem {fact} : Tree.all nonzeroCovered (fun _ => true) 28866 '
                     f'{chunk} {4096*k+64*j} 64 = true := by\n  unfold nonzeroCovered\n  decide +kernel']
        shape = f'sigma{k:02d}_perfect'
        fact = f'coverage{k:02d}'
        shapes.append(shape)
        coverage.append(fact)
        body += [f'theorem {shape} : Frames.AssignmentB.sigma{k:02d}.Perfect 4096 := by\n'
                 f'  exact {perfect(parts)}',
                 f'theorem {fact} : Tree.all nonzeroCovered (fun _ => true) 28866 '
                 f'Frames.AssignmentB.sigma{k:02d} {4096*k} 4096 = true := by\n'
                 '  change ' + conjunction([f'Tree.all nonzeroCovered (fun _ => true) 28866 '
                     f'Frames.AssignmentB.sigma{k:02d}_{j:02d} {4096*k+64*j} 64' for j in range(64)])
                 + ' = true\n  rw [' + ', '.join(facts) + ']\n  rfl']
        write(f'ChecksKeyB/{name}.lean', [prefix + '.ReadoutCoverageKernelB'], body)
    write('ReadoutCoverageChecksB.lean', imports, [
        'theorem sigmaTable_perfect : Frames.AssignmentB.sigmaTable.Perfect 32768 := by\n'
        f'  exact {perfect(shapes)}',
        'theorem nonzero_coverage : Tree.all nonzeroCovered (fun _ => true) 28866 '
        'Frames.AssignmentB.sigmaTable 0 32768 = true := by\n  change '
        + conjunction([f'Tree.all nonzeroCovered (fun _ => true) 28866 '
                       f'Frames.AssignmentB.sigma{k:02d} {4096*k} 4096' for k in range(8)])
        + ' = true\n  rw [' + ', '.join(coverage) + ']\n  rfl'])
