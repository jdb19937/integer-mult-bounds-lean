#!/usr/bin/env python3
"""Emit canonical-chain membership checks; reuse the pinned frame and slot tables."""
import argparse
import json
from pathlib import Path

import stage2designb


def conjunction(xs):
    if len(xs) == 1:
        return xs[0]
    mid = len(xs) // 2
    return '(' + conjunction(xs[:mid]) + ' && ' + conjunction(xs[mid:]) + ')'


def emit(destination):
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Frames.AuxCoverageB'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Frames/AuxCoverageB'
    for kind, count, table, size in [('Nodes', 16, 'arguments', 'nodeCount'), ('Slots', 8, 'slots', 'GeometryB.slotCount'), ('Roots', 8, 'endpoints', 'rootCount')]:
        width = 1024 if kind == 'Roots' else 4096
        pieces = width // 128
        for k in range(count):
            namespace = 'Local.SlotAssignmentB' if kind == 'Nodes' else 'GeometryB'
            checker = {'Nodes': 'nodeOk', 'Slots': 'slotOk', 'Roots': 'rootOk'}[kind]
            terms, facts = [], []
            for j in range(pieces):
                tree = f'{namespace}.{table}{k:02d}_{j:02d}'
                term = f'Tree.all {checker} (fun _ => true) {size} {tree} {width*k+128*j} 128'
                terms.append(term)
                facts.append(f'theorem {table}{k:02d}_{j:02d}_checked : {term} = true := by\n'
                             f'  unfold {checker}\n  decide +kernel')
            tree = f'{namespace}.{table}{k:02d}'
            names = [f'{table}{k:02d}_{j:02d}_checked' for j in range(pieces)]
            facts.append(f'theorem {table}{k:02d}_checked : Tree.all {checker} (fun _ => true) {size}\n'
                         f'    {tree} {width*k} {width} = true := by\n'
                         f'  change {conjunction(terms)} = true\n  rw [' + ', '.join(names) + ']\n  decide')
            path = root / 'Checks' / f'{kind}{k:02d}.lean'
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text('module\n\npublic import ' + prefix + '.Kernel\n\n'
                f'/-! Generated by scripts/pr97/designbauxcoverage.py; pinned upstream {stage2designb.UPSTREAM}.\n'
                f'Pinned hashes {json.dumps(stage2designb.PINS, sort_keys=True)}.\n'
                'No new frame data: membership checks reuse the existing signed chains. -/\n'
                '@[expose] public section\nnamespace ' + prefix + '\nnoncomputable section\nopen Local\n\n' +
                '\n\n'.join(facts) + '\nend\nend ' + prefix + '\n')
    emit_checked(root, prefix)
    print('emitted 32 auxiliary coverage check modules', flush=True)


def emit_checked(root, prefix):
    imports = [prefix + '.Checks.' + kind + f'{k:02d}'
               for kind, count in [('Nodes', 16), ('Slots', 8), ('Roots', 8)]
               for k in range(count)]
    body = []
    configurations = [
        ('nodeOk', 'n', 64042, 16, 4096, 'Local.SlotAssignmentB', 'arguments', 'argumentSlots', 65536, 'nodeCount'),
        ('slotOk', 's', 28866, 8, 4096, 'GeometryB', 'slots', 'slotTree', 32768, 'GeometryB.slotCount'),
        ('rootOk', 'j', 5336, 8, 1024, 'GeometryB', 'endpoints', 'endpointTree', 8192, 'rootCount'),
    ]
    for checker, var, bound, chunks, width, ns, piece, tree, fullwidth, size in configurations:
        lines = [f'theorem {checker}_at ({var} : Nat) (h : {var} < {size}) :',
                 f'    {checker} {var} ({ns}.{tree}.get {fullwidth} {var}) = true := by',
                 f'  have hb : {var} < {bound} := h',
                 f'  obtain ⟨k, i, hi, rfl⟩ : ∃ k i, i < {width} ∧ {var} = {width} * k + i :=',
                 f'    ⟨{var} / {width}, {var} % {width}, Nat.mod_lt _ (by norm_num), (Nat.div_add_mod {var} {width}).symm⟩',
                 f'  have hk : k < {chunks} := by omega',
                 '  interval_cases k']
        for k in range(chunks):
            get = f'{ns}.{tree}_get_{k:02d}'
            lines += [f'  · rw [{get} i hi]',
                      f'    exact Tree.all_get _ _ _ {ns}.{piece}{k:02d} {width} ({width} * {k})',
                      f'      {ns}.{piece}{k:02d}_perfect {piece}{k:02d}_checked i hi h']
        body.append('\n'.join(lines))
    (root / 'Checked.lean').write_text('module\n\npublic import Mathlib.Tactic.IntervalCases\n' +
        '\n'.join('public import ' + m for m in imports) + '\n\n'
        '/-! Generated canonical-chain membership facts. -/\n'
        '@[expose] public section\nnamespace ' + prefix + '\nnoncomputable section\nopen Local\n\n' +
        '\n\n'.join(body) + '\nend\nend ' + prefix + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--lean-root', type=Path, required=True)
    emit(parser.parse_args().lean_root)
