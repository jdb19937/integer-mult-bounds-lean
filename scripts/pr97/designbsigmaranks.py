"""Emit readout-rank checks against the existing signed bank and assignment tree."""
import json
from pathlib import Path
import stage2designb


def emit(result, destination):
    assert result['source']['upstream'] == stage2designb.UPSTREAM
    assert result['source']['sha256'] == stage2designb.PINS
    prefix='IntegerMultBounds.MathlibTM2.M8.Frames.AssignmentB'
    root=Path(destination)/'IntegerMultBounds/MathlibTM2/M8/Frames/AssignmentB'
    header=(f'/-! Generated by scripts/pr97/designbsigmaranks.py from upstream {stage2designb.UPSTREAM}.\n'
            f'Pinned source hashes {json.dumps(stage2designb.PINS,sort_keys=True)}.\n'
            'Checks reuse existing readout labels and bank bases; no new rank data. -/\n'
            f'@[expose] public section\nnamespace {prefix}\nnoncomputable section\n')
    def write(name, imports, body):
        path=root/name;path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text('module\n\n'+'\n'.join('public import '+m for m in imports)+'\n\n'
                        +header+'\n\n'.join(body)+f'\nend\nend {prefix}\n')
    imports=[];parts=[]
    def conjunction(items):
        if len(items)==1:return items[0]
        mid=len(items)//2
        return '('+conjunction(items[:mid])+' && '+conjunction(items[mid:])+')'
    for k in range(8):
        name=f'SigmaRank{k:02d}';imports.append(prefix+'.Checks.'+name)
        body=[];facts=[];terms=[]
        for j in range(64):
            chunk=f'sigma{k:02d}_{j:02d}'
            fact=f'{chunk}_rank_checked';facts.append(fact)
            term=f'Local.Tree.all sigmaRankOk (fun _ => true) 28866 {chunk} {4096*k+64*j} 64'
            terms.append(term)
            body.append(f'theorem {fact} : {term} = true := by\n  unfold sigmaRankOk\n  decide +kernel')
        body.append(f'theorem sigma{k:02d}_rank_checked : Local.Tree.all sigmaRankOk (fun _ => true) 28866 '
                    f'sigma{k:02d} {4096*k} 4096 = true := by\n'
                    '  change '+conjunction(terms)+' = true\n  rw ['+', '.join(facts)+']\n  rfl')
        parts.append(f'sigma{k:02d}_rank_checked')
        write('Checks/'+name+'.lean',[prefix+'.RankKernel'],body)
    terms=[f'Local.Tree.all sigmaRankOk (fun _ => true) 28866 sigma{k:02d} {4096*k} 4096' for k in range(8)]
    write('RankChecked.lean',imports,[
        'theorem sigma_rank_checked : Local.Tree.all sigmaRankOk (fun _ => true) 28866 sigmaTable 0 32768 = true := by\n'
        '  change '+conjunction(terms)+' = true\n  rw ['+', '.join(parts)+']\n  rfl'])
