#!/usr/bin/env python3
"""Emit the design-B node frames of the PR97 side DAG (stdlib only).

Usage: stage2lift.py PR97_DIR DATA_JSON LEAN_ROOT

PR97_DIR is upstream's `references/partial-gauge/pr97/` (pinned in its `SOURCE.json`); it must
contain `witness_23.json.gz`, whose lift indices `j` mark upstream's lifted additions. DATA_JSON
is generate.py's output for the same witness (the records of `M8/Local/Data`).

A node's slot successors are the nodes that take it as an argument without a donor there, and the
users its donor link hands its operand to; its direct roots are its root uses. The roots that a
node reaches along successors are the roots of its design-B frame `W(R_n)`. A node is lifted when
upstream lifts it and every root it reaches has one centre `c`: its frame is then
`Frames.liftFrame c M r`, with `M` the pairs `{u, w}` of the outputs `(c, {c, u, w})` it reaches
and `r` whether it reaches the retained centre. The nodes that reach two centres keep their plain
frames (`a* = 1.2369·10⁻⁴` against `1.2406·10⁻⁴` with them, `stage2designb.py`); so every lifted
frame is nondegenerate and has its rank by `Frames.liftFrame_rank`, with no computed ranks.

Writes, under LEAN_ROOT/IntegerMultBounds/MathlibTM2/M8/Local/:
* Data/LiftKK.lean and Data/Lift.lean: the lift record of every node, a tree of width 65536;
* Checks/LiftKK.lean: `liftOk` at every node, per subtree of 256 nodes;
* Checks/LiftRoots.lean: `liftRootOk` at every root.
The script runs the same checks first.
"""
import os
import sys

import stage2hist as h
import witness as wit

sys.set_int_max_str_digits(0)

H = 23
WIDTH = 65536
SUB = 4096
LEAFS = 256

HEADER = '''module

{imports}

/-! Generated by `scripts/pr97/stage2lift.py` from `scripts/pr97/generate.py`'s output for the
pinned PR97 witness (`witness_23.json.gz`, SHA-256 {sha}). Data are untrusted until the
accompanying kernel checks pass. -/

@[expose] public section

namespace IntegerMultBounds.MathlibTM2.M8.Local
'''
FOOTER = '\nend IntegerMultBounds.MathlibTM2.M8.Local\n'


def pb(u, w):
    a, b = sorted((u, w))
    assert a < b < H
    return 23 * a + b


def tree_text(vals):
    if len(vals) == 1:
        return '.leaf %s' % vals[0]
    mid = len(vals) // 2
    return '.node (%s) (%s)' % (tree_text(vals[:mid]), tree_text(vals[mid:]))


def top(ns):
    if len(ns) == 1:
        return ns[0]
    mid = len(ns) // 2
    return '.node (%s) (%s)' % (top(ns[:mid]), top(ns[mid:]))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text)


def pair_rank(pairs):
    """points on edges less bipartite components"""
    adj = {}
    for u, w in pairs:
        adj.setdefault(u, []).append(w)
        adj.setdefault(w, []).append(u)
    side, bip = {}, 0
    for v0 in adj:
        if v0 in side:
            continue
        side[v0] = 0
        stack, ok = [v0], True
        while stack:
            x = stack.pop()
            for y in adj[x]:
                if y not in side:
                    side[y] = 1 - side[x]
                    stack.append(y)
                elif side[y] == side[x]:
                    ok = False
        bip += ok
    return len(adj) - bip


def lifts(pr97_dir, D, N, v, nodes, roots):
    path = pr97_dir.rstrip('/') + '/witness_23.json.gz'
    assert wit.sha256(path) == D['source']['sha256'], 'witness and data differ'
    W = wit.Witness(path)
    upstream = {W.new[int(n)] for n in W.raw['j']}

    def donor(k, pos):
        lf = nodes[k].get('linkedFrom', {})
        return lf.get('1' if pos else '0')

    def pred(k, pos):
        d = donor(k, pos)
        return d if d is not None else nodes[k]['args'][pos]

    succ = [set() for _ in range(N)]
    for k in range(v, N):
        for pos in (0, 1):
            succ[pred(k, pos)].add(k)
    direct = [[] for _ in range(N)]
    for j, q in enumerate(roots):
        direct[q['node']].append(('out', q['out'][0], tuple(q['out'][1])) if 'out' in q
                                 else ('ret', q['ret']))
    reach = [None] * N
    for n in reversed(range(N)):
        s = set(direct[n])
        for t in succ[n]:
            assert t > n
            s |= reach[t]
        reach[n] = frozenset(s)
    rec = [None] * N
    for n in upstream:
        cs = {k[1] for k in reach[n]}
        if len(cs) != 1:
            continue
        (c,) = cs
        pairs = sorted(pb(*[q for q in k[2] if q != c]) for k in reach[n] if k[0] == 'out')
        ret = any(k[0] == 'ret' for k in reach[n])
        rec[n] = (c, pairs, ret)
    return rec, pred, succ


def main(pr97_dir, data_path, lean_root):
    D, N, v, nodes, roots = h.load(data_path)
    sha = D['source']['sha256']
    rec, pred, succ = lifts(pr97_dir, D, N, v, nodes, roots)
    lifted = [n for n in range(N) if rec[n]]
    # the Lean checks: lifted predecessors give lifted successors with fewer roots
    for k in range(v, N):
        for pos in (0, 1):
            p = pred(k, pos)
            if rec[p]:
                assert rec[k] and rec[k][0] == rec[p][0], (p, k)
                assert set(rec[k][1]) <= set(rec[p][1]) and (not rec[k][2] or rec[p][2])
    # the support lies in the star of c and avoids the points of the pairs
    for n in lifted:
        c, pairs, ret = rec[n]
        pts = {u for p in pairs for u in divmod(p, 23)}
        assert c not in pts
        for T in h.supp_triples(nodes[n]['supp']):
            assert c in T and not (set(T) - {c}) & pts, n
    for j, q in enumerate(roots):
        r = rec[q['node']]
        if r:
            if 'out' in q:
                c, T = q['out']
                assert r[0] == c and pb(*[x for x in T if x != c]) in r[1]
            else:
                assert r[0] == q['ret'] and r[2]
    dims = {n: (22 if rec[n][2] else 23) - pair_rank([divmod(p, 23) for p in rec[n][1]]) for n in lifted}
    print('lifted', len(lifted), 'pairs', sum(len(rec[n][1]) for n in lifted),
          'rank mass', sum(dims.values()))

    def term(n):
        if n >= N or not rec[n]:
            return 'none'
        c, pairs, ret = rec[n]
        return '(some ⟨%d, 0x%x, %s⟩)' % (c, sum(1 << p for p in pairs), 'true' if ret else 'false')

    base = os.path.join(lean_root, 'IntegerMultBounds', 'MathlibTM2', 'M8', 'Local')
    for kk in range(16):
        text = HEADER.format(imports='public import IntegerMultBounds.MathlibTM2.M8.Local.LiftKernel', sha=sha)
        subs = []
        for i in range(SUB // LEAFS):
            name = 'lift%02d_%02d' % (kk, i)
            lo = SUB * kk + LEAFS * i
            text += 'def %s : Tree (Option LiftRec) :=\n  %s\n\n' % (
                name, tree_text([term(n) for n in range(lo, lo + LEAFS)]))
            subs.append(name)
        text += 'def lift%02d : Tree (Option LiftRec) := %s\n' % (kk, top(subs))
        write(os.path.join(base, 'Data', 'Lift%02d.lean' % kk), text + FOOTER)
    imports = '\n'.join('public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Lift%02d' % kk
                        for kk in range(16))
    text = HEADER.format(imports=imports, sha=sha)
    text += '/-- The lift records of the nodes (width 65536). -/\ndef lifts : Tree (Option LiftRec) := %s\n' % top(
        ['(lift%02d)' % kk for kk in range(16)])
    write(os.path.join(base, 'Data', 'Lift.lean'), text + FOOTER)
    for kk in range(16):
        imports = '\n'.join([
            'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Rec%02d' % kk,
            'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Lift'])
        text = HEADER.format(imports=imports, sha=sha)
        names = []
        for i in range(SUB // LEAFS):
            name = 'liftOk%02d_%02d' % (kk, i)
            names.append(name)
            text += ('theorem %s :\n    Tree.all (liftOk lifts) (fun _ => true) nodeCount rec%02d_%02d %d %d = true := by\n'
                     '  decide +kernel\n\n') % (name, kk, i, SUB * kk + LEAFS * i, LEAFS)
        text += ('/-- Every node of subtree %d passes the lift check. -/\n'
                 'theorem liftOk%02d :\n    Tree.all (liftOk lifts) (fun _ => true) nodeCount rec%02d (4096 * %d) 4096 = true := by\n'
                 '  unfold rec%02d\n'
                 '  simp only [Tree.all_node, Nat.reduceMul, Nat.reduceAdd, Nat.reduceDiv, %s, Bool.and_self]\n'
                 ) % (kk, kk, kk, kk, kk, ', '.join(names))
        write(os.path.join(base, 'Checks', 'Lift%02d.lean' % kk), text + FOOTER)
    imports = '\n'.join(['public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Records',
                         'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Roots',
                         'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Lift'])
    text = HEADER.format(imports=imports, sha=sha)
    text += ('/-- Every root passes the lift check. -/\n'
             'theorem liftRoots :\n    Tree.all (liftRootOk lifts records) (fun _ => true) rootCount roots 0 rootWidth = true := by\n'
             '  decide +kernel\n')
    write(os.path.join(base, 'Checks', 'LiftRoots.lean'), text + FOOTER)


if __name__ == '__main__':
    main(*sys.argv[1:])
