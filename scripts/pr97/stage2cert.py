#!/usr/bin/env python3
"""The rational moment certificate of the stage-2 histogram (stdlib only).

Usage: stage2cert.py HIST_JSON [LEAN_ROOT]

HIST_JSON is stage2hist.py's output, from upstream's `references/partial-gauge/pr97/` at
`463113d675af7410ac91d53a4fed51ec6494eb9a`. With `τ* = 1 - a`, `a = 969/10^7`, the τ-moment is
`Σ_r (n_r/W)(r/m)^τ* = Σ_r (n_r/W)(r/m) exp(a log(m/r))`. For each rank `r` the script picks a
rational `L_r > log(m/r)`, at 10⁻⁹ above, certified by an exponential series of `k_r` terms:
`m/r < Σ_{i<k_r} L_r^i / i!`. With `exp x ≤ 1 + x + x²/2 + 2x³/9` on `[0, 1]`, the rational sum
`Σ_r (n_r/W)(r/m)(1 + y_r + y_r²/2 + 2y_r³/9)`, `y_r = a L_r`, must stay below
`q_τ = 1 - 2/10^8`. The script prints the slack and, given LEAN_ROOT, writes the rows to
`IntegerMultBounds/MathlibTM2/M8/Stage2Histogram.lean`, which `Stage2Moments.lean` checks.
"""
import json
import math
import os
import sys
from fractions import Fraction
from math import factorial

A = Fraction(969, 10 ** 7)
QT = 1 - Fraction(2, 10 ** 8)
UPSTREAM = '463113d675af7410ac91d53a4fed51ec6494eb9a'

HEADER = '''module

public import Mathlib.Data.Nat.Basic

/-!
# The stage-2 rank histogram of the PR97 node

Generated by `scripts/pr97/stage2cert.py` from `stage2hist.py`'s histogram of the plain-frame
PR97 node, built from upstream's `references/partial-gauge/pr97/witness_23.json.gz` at
`{upstream}`, sha256
`{sha}`.

Each row is `(r, n_r, L_r, k_r)`: `n_r` moves of the node have rank `r`, and `L_r / 10⁹` bounds
`log (529 / r)` from above by an exponential series of `k_r` terms. `Stage2Moments` checks every
row; nothing here is trusted.
-/

@[expose] public section

namespace IntegerMultBounds.MathlibTM2.M8.Stage2Moments

/-- The whole-projector rank histogram with its logarithm bounds. -/
def histogram : List (ℕ × ℕ × ℕ × ℕ) := [
'''


def series(L, k):
    return sum(L ** i / factorial(i) for i in range(k))


def main(path, lean_root=None):
    H = json.load(open(path))
    hist = [tuple(x) for x in H['histogram']]
    W, m = H['W'], H['m']
    total = Fraction(0)
    mu1 = Fraction(0)
    rows = []
    for r, c in hist:
        L = Fraction(math.ceil(math.log(m / r) * 10 ** 9) + 1, 10 ** 9)
        k = 1
        while not series(L, k) > Fraction(m, r):
            k += 1
        y = A * L
        assert 0 <= y <= 1
        total += Fraction(c, W) * Fraction(r, m) * (1 + y + y * y / 2 + Fraction(2, 9) * y ** 3)
        mu1 += Fraction(c, W) * Fraction(r, m)
        rows.append((r, c, L * 10 ** 9, k))
    assert total < QT and mu1 < 1
    assert sum(r * c for r, c, _, _ in rows) == H['rankMass']
    print('q1 = %d/%d' % (mu1.numerator, mu1.denominator))
    print('tau-moment bound %.15f, slack below q_tau %.3e' % (float(total), float(QT - total)))
    if lean_root:
        text = HEADER.format(upstream=UPSTREAM, sha=H['source']['sha256'])
        text += ',\n'.join('  (%d, %d, %d, %d)' % row for row in rows)
        text += ']\n\nend IntegerMultBounds.MathlibTM2.M8.Stage2Moments\n'
        out = os.path.join(lean_root, 'IntegerMultBounds', 'MathlibTM2', 'M8', 'Stage2Histogram.lean')
        with open(out, 'w') as fh:
            fh.write(text)


if __name__ == '__main__':
    main(*sys.argv[1:])
