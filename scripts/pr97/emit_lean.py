#!/usr/bin/env python3
"""Emit the Lean data and check modules of the PR97 witness from generate.py's JSON.

Usage: emit_lean.py DATA_JSON LEAN_ROOT

Writes, under LEAN_ROOT/IntegerMultBounds/MathlibTM2/M8/Local/:
* Data/RecKK.lean (16 subtrees of 4096 node records), Data/Records.lean (the tree of width
  65536), Data/Roots.lean (the root tree of width 8192);
* Checks/NodesKK.lean (one `decide +kernel` theorem per subtree), Checks/Roots.lean.
The record layout is the one documented in `M8/Local/Kernel.lean`.
"""
import json
import os
import sys
from itertools import combinations

sys.set_int_max_str_digits(0)

H = 23
TRIP = list(combinations(range(H), 3))
TID = {T: i for i, T in enumerate(TRIP)}
WIDTH = 65536
SUB = 4096
LEAFS = 256
ROOTW = 8192


def pb(u, w):
    """bit of the pair {u, w} in the 23x23 upper-triangle layout."""
    a, b = sorted((u, w))
    assert a < b < H
    return 23 * a + b


def pmask_23(c, P22):
    """convert generate.py's 22x22 rank-relative mask to the 23x23 layout."""
    rk_inv = [u for u in range(H) if u != c]
    m = 0
    for i in range(22):
        for j in range(i + 1, 22):
            if P22 >> (22 * i + j) & 1:
                m |= 1 << pb(rk_inv[i], rk_inv[j])
    return m


def lean_bool(b):
    return 'true' if b else 'false'


def node_record(rec, root_index):
    """the Lean term of a node record (see M8/Local/Kernel.lean)."""
    is_add = 'args' in rec
    a, b = rec['args'] if is_add else (0, 0)
    L = rec.get('link')
    if L:
        paths = ', '.join('⟨%d, %d, %d, %d⟩' % tuple(p) for p in L.get('relations', []))
        link = 'some ⟨%s, %d, %s, %d, [%s]⟩' % (lean_bool(L['operand'] == 1), L['user'],
                                                lean_bool(L['pos'] == 1), L.get('point', 0), paths)
    else:
        link = 'none'
    lf = rec.get('linkedFrom', {})
    d0 = 'some %d' % lf['0'] if '0' in lf else 'none'
    d1 = 'some %d' % lf['1'] if '1' in lf else 'none'
    f = rec['free']
    if f[0] == 'gate':
        free = '.gate %d %s' % (f[1], lean_bool(f[2] == 1))
    else:
        key = ('out', f[1], tuple(f[2])) if f[0] == 'out' else ('ret', f[1])
        free = '.root %d' % root_index[key]
    sp = rec['supp']
    if sp[0] == 'leaf':
        supp = '.three %d %d %d' % TRIP[sp[1]]
    elif sp[0] == 'two':
        supp = '.two %d %d %d' % (sp[1], sp[2], sp[3])
    else:
        supp = '.one %d 0x%x' % (sp[1], pmask_23(sp[1], sp[2]))
    return '⟨%s, %d, %d, %s, %s, %s, %s, %s⟩' % (lean_bool(is_add), a, b, link, d0, d1, free, supp)


PAD_NODE = '⟨false, 0, 0, none, none, none, .root 0, .three 0 0 0⟩'
PAD_ROOT = '⟨0, 0, none⟩'


def tree_text(vals):
    """a balanced tree literal over a power-of-two list of entry terms."""
    if len(vals) == 1:
        return '.leaf %s' % vals[0]
    mid = len(vals) // 2
    return '.node (%s) (%s)' % (tree_text(vals[:mid]), tree_text(vals[mid:]))


HEADER = '''module

public import IntegerMultBounds.MathlibTM2.M8.Local.TreeFacts{imports}

/-! Generated by `scripts/pr97/emit_lean.py` from `scripts/pr97/generate.py`'s output for the
pinned PR97 witness (`witness_23.json.gz`, SHA-256 {sha}). Data are untrusted until the
accompanying kernel checks pass. -/

@[expose] public section

namespace IntegerMultBounds.MathlibTM2.M8.Local
'''
FOOTER = '\nend IntegerMultBounds.MathlibTM2.M8.Local\n'


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text)


def top(ns):
    """a balanced tree over named subtrees."""
    if len(ns) == 1:
        return ns[0]
    mid = len(ns) // 2
    return '.node (%s) (%s)' % (top(ns[:mid]), top(ns[mid:]))


def main(data_path, lean_root):
    with open(data_path) as fh:
        D = json.load(fh)
    sha = D['source']['sha256']
    base = os.path.join(lean_root, 'IntegerMultBounds', 'MathlibTM2', 'M8', 'Local')
    # roots in canonical order
    roots = [None] * (3 * len(TRIP) + H)
    for q in D['roots']:
        if 'out' in q:
            c, T = q['out']
            j = 3 * TID[tuple(T)] + T.index(c)
        else:
            j = 3 * len(TRIP) + q['ret']
        assert roots[j] is None
        roots[j] = q
    assert all(roots)
    root_index = {}
    rvals = []
    for j, q in enumerate(roots):
        if 'out' in q:
            c, T = q['out']
            a, b = [x for x in T if x != c]
            rvals.append('⟨%d, %d, some (%d, %d)⟩' % (q['node'], c, a, b))
            root_index['out', c, tuple(T)] = j
        else:
            rvals.append('⟨%d, %d, none⟩' % (q['node'], q['ret']))
            root_index['ret', q['ret']] = j
    assert len(rvals) == 5336
    rvals += [PAD_ROOT] * (ROOTW - len(rvals))
    vals = [node_record(rec, root_index) for rec in D['nodes']]
    assert len(vals) == D['N']
    vals += [PAD_NODE] * (WIDTH - len(vals))
    mods = []
    for k in range(WIDTH // SUB):
        chunk = vals[k * SUB:(k + 1) * SUB]
        body = []
        for j in range(SUB // LEAFS):
            body.append('def rec%02d_%02d : Tree NodeRec :=\n  %s\n' %
                        (k, j, tree_text(chunk[j * LEAFS:(j + 1) * LEAFS])))
        names = ['rec%02d_%02d' % (k, j) for j in range(SUB // LEAFS)]
        body.append('/-- Node records %d to %d. -/\ndef rec%02d : Tree NodeRec := %s\n' %
                    (k * SUB, (k + 1) * SUB - 1, k, top(names)))
        body.append('theorem rec%02d_perfect : rec%02d.Perfect %d :=\n'
                    '  Tree.perfect_of_perfectB _ _ (by decide +kernel)\n' % (k, k, SUB))
        write(os.path.join(base, 'Data', 'Rec%02d.lean' % k),
              HEADER.format(imports='', sha=sha) + '\n'.join(body) + FOOTER)
        mods.append('Rec%02d' % k)
    imports = ''.join('\npublic import IntegerMultBounds.MathlibTM2.M8.Local.Data.%s' % m
                      for m in mods)
    lemmas = []
    for k in range(WIDTH // SUB):
        lemmas.append('theorem records_get_%02d (i : ℕ) (hi : i < %d) :\n'
                      '    records.get %d (%d * %d + i) = rec%02d.get %d i := by\n'
                      '  unfold records\n  simp only [Tree.get_node]\n'
                      '  split_ifs <;> first | (exfalso; omega) | exact Tree.get_congr (by norm_num) (by omega)\n'
                      % (k, SUB, WIDTH, SUB, k, k, SUB))
    write(os.path.join(base, 'Data', 'Records.lean'),
          HEADER.format(imports=imports, sha=sha) +
          '\n/-- The node records in compile order (width %d). -/\ndef records : Tree NodeRec := %s\n\n' %
          (WIDTH, top(['rec%02d' % k for k in range(WIDTH // SUB)])) + '\n'.join(lemmas) + FOOTER)
    rbody = []
    for j in range(ROOTW // LEAFS):
        rbody.append('def roots_%02d : Tree RootRec :=\n  %s\n' %
                     (j, tree_text(rvals[j * LEAFS:(j + 1) * LEAFS])))
    rbody.append('/-- The root records in canonical order (width %d). -/\ndef roots : Tree RootRec := %s\n' %
                 (ROOTW, top(['roots_%02d' % j for j in range(ROOTW // LEAFS)])))
    rbody.append('theorem roots_perfect : roots.Perfect %d :=\n'
                 '  Tree.perfect_of_perfectB _ _ (by decide +kernel)\n' % ROOTW)
    write(os.path.join(base, 'Data', 'Roots.lean'),
          HEADER.format(imports='', sha=sha) + '\n'.join(rbody) + FOOTER)
    data_imports = ('\npublic import IntegerMultBounds.MathlibTM2.M8.Local.Data.Records'
                    '\npublic import IntegerMultBounds.MathlibTM2.M8.Local.Data.Roots')
    for k in range(WIDTH // SUB):
        if k * SUB >= D['N']:
            continue
        txt = (HEADER.format(imports=data_imports, sha=sha) +
               '\ntheorem nodes%02d :\n    Tree.all (allOk records roots) NodeRec.isPad nodeCount rec%02d (4096 * %d) 4096 = true := by\n'
               '  decide +kernel\n' % (k, k, k) + FOOTER)
        write(os.path.join(base, 'Checks', 'Nodes%02d.lean' % k), txt)
    write(os.path.join(base, 'Checks', 'Roots.lean'),
          HEADER.format(imports=data_imports, sha=sha) +
          '\ntheorem roots_ok :\n    Tree.all (rootOk records) RootRec.isPad rootCount roots 0 rootWidth = true := by\n'
          '  decide +kernel\n' + FOOTER)
    print('records', D['N'], 'roots', len(roots))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
