#!/usr/bin/env python3
"""Emit local XOR certificates from the pinned design-B compiler reconstruction.

Inputs are reconstructed by generate.py and designbword.py from the upstream
revision pinned in stage2designb.py. No machine-local cache path is assumed.
"""
import hashlib
import json
from itertools import combinations
from pathlib import Path

import designbword
import stage2designb


def coefficients(dag, compiled, root_masks):
    """Backward use recurrence, independently compared with emitted side operations."""
    n, v, count = dag['N'], dag['v'], dag['R']
    assert len(root_masks) == len(dag['roots'])
    assert len(compiled['servingOrders']) == n
    arguments = [[0, 0] for _ in range(n)]
    node_masks = [0] * n

    def use(u):
        return root_masks[u[1]] if u[0] == 'root' else arguments[u[1]][int(u[2])]

    for k in reversed(range(n)):
        for u in compiled['servingOrders'][k]:
            if u[0] == 'gate':
                assert u[1] > k
            node_masks[k] ^= use(u)
        if k >= v:
            arguments[k] = [node_masks[k], node_masks[k]]
            link = dag['nodes'][k].get('link')
            if link:
                assert k < link['user'] < n
                arguments[k][link['operand']] ^= arguments[link['user']][link['pos']]

    slots = [None] * count
    for k, us in enumerate(compiled['servingOrders']):
        assert us
        for i, u in enumerate(us):
            if k >= v and i == 0:
                continue
            s = compiled['slotsBefore'][k] + i - (k >= v)
            assert slots[s] is None
            slots[s] = use(u)
    assert all(m is not None for m in slots)

    replay = [0] * count
    for s, m in zip(compiled['rootSlots'], root_masks, strict=True):
        replay[s] ^= m
    for op in reversed(compiled['side']):
        kind, p, q, _ = op
        assert p != q
        if kind == 'add':
            replay[q] ^= replay[p]
        else:
            assert kind == 'copy'
            replay[p] ^= replay[q]
    assert replay == slots, 'use recurrence disagrees with actual compiler side adjoint'
    return arguments, slots


def conjunction(items):
    if len(items) == 1:
        return items[0]
    mid = len(items) // 2
    return f"({conjunction(items[:mid])} && {conjunction(items[mid:])})"


def emit(result, compiled, dag, destination):
    assert result['source']['upstream'] == stage2designb.UPSTREAM
    assert result['source']['sha256'] == stage2designb.PINS
    assert dag['source']['sha256'] == stage2designb.PINS['witness_23.json.gz']
    assert dag['h'] == 23 and dag['v'] == 1771
    triples = list(combinations(range(dag['h']), 3))
    centres = [sum(1 << t for t, triple in enumerate(triples) if c in triple)
               for c in range(dag['h'])]
    root_masks = [1 << (j // 3) for j in range(3 * dag['v'])] + centres
    arguments, slots = coefficients(dag, compiled, root_masks)
    masks = sorted({0, *root_masks, *slots, *(m for pair in arguments for m in pair)})
    ids = {m: i for i, m in enumerate(masks)}
    payload = {'masks': masks, 'arguments': arguments, 'slots': slots, 'centres': centres}
    digest = hashlib.sha256(json.dumps(payload, separators=(',', ':')).encode()).hexdigest()
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Local'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Local'
    opening = (f'/-! Generated by scripts/pr97/designbcovariance.py from upstream {stage2designb.UPSTREAM}.\n'
               f'Witness SHA-256 {stage2designb.PINS["witness_23.json.gz"]};\n'
               f'schedule SHA-256 {stage2designb.PINS["deferred_23.json.gz"]}.\n'
               f'Canonical coefficient SHA-256 {digest}.\n'
               'Data are untrusted until the local kernel checks pass. -/\n'
               '@[expose] public section\n'
               f'namespace {prefix}.CovarianceB\nnoncomputable section\n')

    def write(name, imports, body):
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('module\n\n' + '\n'.join('public import ' + m for m in imports)
                        + '\n\n' + opening + '\n\n'.join(body) + f'\nend\nend {prefix}.CovarianceB\n')

    imports, tables = [], []
    for stem, vals, width, typ, pad in [
        ('masks', [hex(m) for m in masks], 65536, 'Nat', '0'),
        ('arguments', [f'({ids[a]}, {ids[b]})' for a, b in arguments], 65536, 'Nat × Nat', '(0, 0)'),
        ('slots', [str(ids[m]) for m in slots], 32768, 'Nat', '0'),
    ]:
        assert len(vals) <= width
        vals += [pad] * (width - len(vals))
        parts = []
        for i in range(width // 4096):
            name = f'{stem.title()}{i:02d}'
            imports.append(prefix + '.DataCovB.' + name)
            body, chunks = [], []
            for j in range(32):
                chunk = f'{stem}{i:02d}_{j:02d}'
                chunks.append(chunk)
                start = 4096 * i + 128 * j
                body.append(f'def {chunk} : Tree ({typ}) := ' + designbword.tree_text(vals[start:start + 128]))
            part = f'{stem}{i:02d}'
            parts.append(part)
            body.append(f'def {part} : Tree ({typ}) := ' + designbword.top(chunks))
            write(f'DataCovB/{name}.lean', [prefix + '.Kernel'], body)
        tables.append(f'def {stem} : Tree ({typ}) := ' + designbword.top(parts))
    tables += [
        'def maskAt (i : Nat) : Nat := masks.get 65536 i',
        'def argumentMask (n : Nat) (pos : Bool) : Nat :=\n'
        '  let x := arguments.get 65536 n\n  maskAt (if pos then x.2 else x.1)',
        'def slotMask (s : Nat) : Nat := if s < 28866 then maskAt (slots.get 32768 s) else 0',
        'def centres : Tree Nat := ' + designbword.tree_text([str(ids[m]) for m in centres] + ['0'] * 9),
        'def rootMask (j : Nat) : Nat :=\n'
        '  if j < 3 * leafCount then Nat.shiftLeft 1 (j / 3) else maskAt (centres.get 32 (j - 3 * leafCount))',
        'def coefficientMasks : Masks := ⟨argumentMask, rootMask, slotMask⟩',
    ]
    write('DataCovB/Tables.lean', imports + [prefix + '.CovarianceKernelB'], tables)
    all_checks, aggregates = [], []
    for i in range(16):
        body, facts = [], []
        name = f'Nodes{i:02d}'
        all_checks.append(prefix + '.ChecksCovB.' + name)
        for j in range(32):
            fact = f'covariance{i:02d}_{j:02d}'
            facts.append(fact)
            body.append(f'theorem {fact} : Tree.all (nodeOk coefficientMasks) (fun _ => true) '
                        f'nodeCount bdata{i:02d}_{j:02d} {4096*i+128*j} 128 = true := by\n'
                        '  unfold nodeOk\n  decide +kernel')
        body.append(f'theorem covariance{i:02d} : Tree.all (nodeOk coefficientMasks) '
                    f'(fun _ => true) nodeCount bdata{i:02d} {4096*i} 4096 = true := by\n'
                    '  change ' + conjunction([f'Tree.all (nodeOk coefficientMasks) (fun _ => true) '
                        f'nodeCount bdata{i:02d}_{j:02d} {4096*i+128*j} 128' for j in range(32)])
                    + ' = true\n  rw [' + ', '.join(facts) + ']\n  rfl')
        write(f'ChecksCovB/{name}.lean', [prefix + '.DataCovB.Tables'], body)
        aggregates.append(f'covariance{i:02d}')
    write('CovarianceChecksB.lean', all_checks,
          ['theorem covariance_checked : Tree.all (nodeOk coefficientMasks) (fun _ => true) '
           'nodeCount bdata 0 width = true := by\n  change '
           + conjunction([f'Tree.all (nodeOk coefficientMasks) (fun _ => true) '
               f'nodeCount bdata{i:02d} {4096*i} 4096' for i in range(16)])
           + ' = true\n  rw [' + ', '.join(aggregates) + ']\n  rfl'])
    centre_checks = [f'theorem centre{c:02d}_checked : centreOk coefficientMasks {c} = true := by\n'
                     '  unfold centreOk\n  decide +kernel' for c in range(dag['h'])]
    expr = 'true'
    for c in reversed(range(dag['h'])):
        expr = f'(centreOk coefficientMasks {c} && {expr})'
    centre_checks.append('theorem centres_checked : (List.range 23).all (centreOk coefficientMasks) = true := by\n'
                         f'  change {expr} = true\n  rw ['
                         + ', '.join(f'centre{c:02d}_checked' for c in range(dag['h'])) + ']\n  rfl')
    write('CovarianceRootChecksB.lean', [prefix + '.DataCovB.Tables'], centre_checks)
    print(f'covariance: {len(masks)} masks, {len(arguments)} argument pairs, {len(slots)} slots; SHA-256 {digest}')
