"""Emit source path checks using leaf allocation intervals and existing signed chains."""
import hashlib
import json
from pathlib import Path

import designbword
import stage2designb


def emit(result, destination):
    assert result['source']['upstream'] == stage2designb.UPSTREAM
    assert result['source']['sha256'] == stage2designb.PINS
    starts = []
    for n in range(1771):
        kind, index, chain = result['fullChains'][30637+n]
        assert (kind, index) == ('x', n+1)
        assert chain[0][0] == 2 and chain[-1] == [1, 0]
        starts.append(chain[0][1])
    digest = hashlib.sha256(json.dumps(starts, separators=(',', ':')).encode()).hexdigest()
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Frames.SourceGeometryB'
    root = Path(destination)/'IntegerMultBounds/MathlibTM2/M8/Frames/SourceGeometryB'
    header = (f'/-! Generated by scripts/pr97/designbsourcegeometry.py from upstream {stage2designb.UPSTREAM}.\n'
              f'Pinned source hashes {json.dumps(stage2designb.PINS,sort_keys=True)}.\n'
              f'Canonical source-start SHA-256 {digest}.\n'
              'Source paths reuse existing signed chains and certified bank entries. -/\n'
              f'@[expose] public section\nnamespace {prefix}\nnoncomputable section\n')

    def write(name, imports, body):
        path=root/name
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text('module\n\n'+'\n'.join('public import '+m for m in imports)+'\n\n'
                        +header+'\n\n'.join(body)+f'\nend\nend {prefix}\n')

    vals=list(map(str,starts))+['0']*(2048-len(starts))
    data, names = [], []
    for i in range(16):
        name=f'starts{i:02d}'
        names.append(name)
        data.append(f'def {name} : Local.Tree Nat := '+designbword.tree_text(vals[128*i:128*(i+1)]))
    data.append('def starts : Local.Tree Nat := '+designbword.top(names))
    data.append('def sourceStart (n : Nat) : Nat := starts.get 2048 n')
    write('Data.lean',[prefix+'.Kernel'],data)
    imports, ranges = [], []
    for start in range(0,1771,32):
        size=min(32,1771-start)
        k=start//32
        imports.append(prefix+f'.Checks.Sources{k:02d}')
        body=[]
        for n in range(start,start+size):
            body.append(f'theorem sourceOk_{n} : sourceOk {n} (sourceStart {n}) = true := by\n'
                        '  unfold sourceOk\n  decide +kernel')
        name=f'sources{k:02d}_checked'
        body.append(f'theorem {name} : (List.range\' {start} {size}).all (fun n => sourceOk n (sourceStart n)) = true := by\n'
                    '  change ('+' && ('.join(f'sourceOk {n} (sourceStart {n})' for n in range(start,start+size))
                    +' && true'+')'*size+' = true\n'
                    '  rw ['+', '.join(f'sourceOk_{n}' for n in range(start,start+size))+']\n  rfl')
        write(f'Checks/Sources{k:02d}.lean',[prefix+'.Data'],body)
        ranges.append((start,size,name))
    facts=[]
    def merge(parts):
        if len(parts)==1:
            return parts[0]
        mid=len(parts)//2
        n,a,ha=merge(parts[:mid]);m,b,hb=merge(parts[mid:])
        assert m==n+a
        name=f'source_range_{n}_{a+b}'
        facts.append(f'theorem {name} : (List.range\' {n} {a+b}).all (fun n => sourceOk n (sourceStart n)) = true :=\n'
                     f'  TargetGeometryB.all_range_merge _ {n} {a} {b} {ha} {hb}')
        return n,a+b,name
    _,_,final=merge(ranges)
    facts.append('theorem sourceOk_at (n : Nat) (hn : n < 1771) : sourceOk n (sourceStart n) = true := by\n'
                 f'  apply List.all_eq_true.mp {final} n\n  exact List.mem_range\'.mpr ⟨n, hn, by omega⟩')
    write('Checked.lean',imports+['IntegerMultBounds.MathlibTM2.M8.Frames.TargetGeometryB.RangeFacts'],facts)
    print('source paths:',len(starts),';',digest)
