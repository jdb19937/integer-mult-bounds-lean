"""Emit checked block hints and full-chain endpoints for design-B targets."""
import hashlib
import json
from itertools import combinations
from pathlib import Path

import designbcovariance
import stage2designb


def emit(result, compiled, dag, destination):
    assert result['source']['upstream'] == stage2designb.UPSTREAM
    assert result['source']['sha256'] == stage2designb.PINS
    assert dag['source']['sha256'] == stage2designb.PINS['witness_23.json.gz']
    triples = list(combinations(range(23), 3))
    roots = [1 << (j//3) for j in range(3*1771)] + [
        sum(1 << t for t, T in enumerate(triples) if c in T) for c in range(23)]
    _, masks = designbcovariance.coefficients(dag, compiled, roots)
    slot = dict(compiled['slotMap'])
    sigma = {slot[s]: tuple(f) for s, f in enumerate(result['sigma'])}
    order = sorted(compiled['deferred'], key=lambda s: sigma[s] != (0, 0))
    hints = []
    for start in range(0, len(order), 32):
        mask = 0
        for s in order[start:start+32]:
            mask |= masks[s]
        hints.append(mask)
    digest = hashlib.sha256(json.dumps({'order': order, 'hints': hints},
                                     separators=(',', ':')).encode()).hexdigest()
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Frames.TargetGeometryB'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Frames/TargetGeometryB'
    header = (f'/-! Generated by scripts/pr97/designbtargetgeometry.py from upstream {stage2designb.UPSTREAM}.\n'
              f'Pinned source hashes {json.dumps(stage2designb.PINS, sort_keys=True)}.\n'
              f'Canonical readout-block SHA-256 {digest}.\n'
              'Each block mask is untrusted until its covering check passes. -/\n'
              f'@[expose] public section\nnamespace {prefix}\nnoncomputable section\n')

    def write(name, imports, body):
        path = root/name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('module\n\n'+'\n'.join('public import '+m for m in imports)+'\n\n'
                        +header+'\n\n'.join(body)+f'\nend\nend {prefix}\n')

    pieces = (len(order)+127)//128
    data_imports, check_imports, piece_names, slot_facts, check_facts = [], [], [], [], []
    for k in range((pieces+7)//8):
        name = f'Hints{k:02d}'
        data_imports.append(prefix+'.Data.'+name)
        check_imports.append(prefix+'.Checks.'+name)
        data, checks = [], []
        for j in range(8*k, min(8*(k+1), pieces)):
            chunk = f'Frames.AssignmentB.readoutOrder{j:03d}'
            name = f'hints{j:03d}'
            piece_names.append(name)
            fields = []
            for i in range(4):
                mask = hints[4*j+i] if 4*j+i < len(hints) else 0
                slots = f'{chunk}.drop {32*i}' if i == 3 else f'({chunk}.drop {32*i}).take 32'
                fields.append(f'⟨{hex(mask)}, {slots}⟩')
            data.append(f'def {name} : List Hint := ['+', '.join(fields)+']')
            slot_facts.append(name+'_slots')
            data.append(f'theorem {name}_slots : {name}.flatMap Hint.slots = {chunk} := by\n'
                        f'  simpa only [{name}, List.flatMap_cons, List.flatMap_nil, List.append_nil, List.drop_zero, List.append_assoc]\n'
                        f'    using split_four {chunk}')
            fact = name+'_checked'
            check_facts.append(fact)
            checks.append(f'theorem {fact} : {name}.all Hint.covers = true := by\n'
                          '  unfold Hint.covers\n  decide +kernel')
        write(f'Data/Hints{k:02d}.lean', [prefix+'.HintFacts'], data)
        write(f'Checks/Hints{k:02d}.lean', [prefix+f'.Data.Hints{k:02d}'], checks)
    write('HintData.lean', data_imports, [
        'def hints : List Hint := '+' ++ '.join(piece_names),
        'theorem hints_slots : hints.flatMap Hint.slots = Frames.AssignmentB.readoutOrder := by\n'
        '  simp only [hints, List.flatMap_append, '+', '.join(slot_facts)+', Frames.AssignmentB.readoutOrder]',
    ])
    write('HintChecked.lean', check_imports+[prefix+'.HintData'], [
        'theorem hints_checked : hints.all Hint.covers = true := by\n'
        '  simp only [hints, List.all_append, '+', '.join(check_facts)+', Bool.true_and]',
    ])
    print('target block hints:', pieces, 'readout chunks;', digest)

    # Endpoints reuse the already certified full target chains, including repeats.
    endpoints = []
    for t in range(len(triples)):
        kind, index, chain = result['fullChains'][28866+t]
        assert (kind, index) == ('y', t)
        assert chain[-1][0] == 3
        endpoints.append(chain[-1][1])
    endpoint_digest = hashlib.sha256(json.dumps(endpoints, separators=(',', ':')).encode()).hexdigest()
    write('Endpoints.lean', [prefix+'.Kernel'], [
        f'/- Endpoint list SHA-256 {endpoint_digest}. -/',
        'def endpoints : List Nat := ['+', '.join(map(str, endpoints))+']',
        'def endpoint (t : Nat) : Nat := endpoints[t]?.getD 0',
    ])
    imports, ranges = [], []
    for start in range(0, len(endpoints), 8):
        size = min(8, len(endpoints)-start)
        k = start//8
        imports.append(prefix+f'.Checks.Targets{k:03d}')
        body, facts = [], []
        for t in range(start, start+size):
            fact = f'targetOk_{t}'
            facts.append(fact)
            body.append(f'theorem {fact} : targetOk {t} (endpoint {t}) = true := by\n'
                        '  unfold targetOk\n  decide +kernel')
        name = f'targets{k:03d}_checked'
        body.append(f'theorem {name} : (List.range\' {start} {size}).all (fun t => targetOk t (endpoint t)) = true := by\n'
                    '  change ('+' && ('.join(f'targetOk {t} (endpoint {t})' for t in range(start,start+size))+' && true'+')'*size+' = true\n'
                    '  rw ['+', '.join(facts)+']\n  rfl')
        write(f'Checks/Targets{k:03d}.lean', [prefix+'.Endpoints'], body)
        ranges.append((start, size, name))
    aggregates = []
    def merge(parts):
        if len(parts) == 1:
            return parts[0]
        mid = len(parts)//2
        n, a, ha = merge(parts[:mid])
        m, b, hb = merge(parts[mid:])
        assert m == n+a
        name = f'target_range_{n}_{a+b}'
        aggregates.append(f'theorem {name} : (List.range\' {n} {a+b}).all (fun t => targetOk t (endpoint t)) = true :=\n'
                          f'  all_range_merge _ {n} {a} {b} {ha} {hb}')
        return n, a+b, name
    _, _, final = merge(ranges)
    aggregates.append('theorem targetOk_at (t : Nat) (ht : t < 1771) : targetOk t (endpoint t) = true := by\n'
                      f'  apply List.all_eq_true.mp {final} t\n  exact List.mem_range\'.mpr ⟨t, ht, by omega⟩')
    write('Checked.lean', imports+[prefix+'.RangeFacts'], aggregates)
    print('target endpoint checks:', len(endpoints), ';', endpoint_digest)
