#!/usr/bin/env python3
"""Emit the data of the design-B word of the PR97 side slots (stdlib only).

Usage: designbword.py PR97_DIR DATA_JSON LEAN_ROOT

PR97_DIR is upstream's `references/partial-gauge/pr97/` at
`463113d675af7410ac91d53a4fed51ec6494eb9a` (pins in `stage2designb.py`); DATA_JSON is
`generate.py`'s output for the same witness. The design-B schedule (`deferred_23.json.gz`) is
read as a plan for the Lean compiler of `M8/Local/Compile.lean`:
* the serving order of every node that copies: the use that keeps the node's slot (the last late
  user of a late copy, the first free use otherwise), then the copies in the order of their
  starting frame dimensions (stable), as upstream's ledger expands them;
* the phase bits: an addition in the first phase (`Φ`, bit 0) when upstream's phase one runs it,
  a copy (`Ψ`, bit 1) when it runs the node's fan;
* the deferred uses in readout order, and the uses of the V gates, early and deferred, in
  upstream's orders.
The script compiles the DAG as `Dag.compile` does with that order, maps upstream's slots to the
compiled ones (equal histories), checks the local phase conditions of `M8/Local/Phase.lean` and
the conditions of `Dag.wordB_run`, and replays the design-B word over F2 on random contents.

Writes, under LEAN_ROOT/IntegerMultBounds/MathlibTM2/M8/Local/:
* DataB/BDataKK.lean (16 subtrees of 4096 entries `(phase bits, serving order)`), DataB/BData.lean
  (the tree of width 65536 and the use lists);
* ChecksB/NodesKK.lean, ChecksB/Deferred.lean (`decide +kernel` checks).
"""
import gzip
import hashlib
import json
import os
import random
import sys
from collections import defaultdict
from itertools import combinations

import stage2designb as sd
import witness as wit

sys.set_int_max_str_digits(0)

H = 23
WIDTH = 65536
SUB = 4096
LEAFS = 256
DCHUNK = 3000

HEADER = '''module

{imports}

/-! Generated by `scripts/pr97/designbword.py` from upstream's design-B schedule
(`deferred_23.json.gz`, SHA-256 {dsha}) and `scripts/pr97/generate.py`'s output for the pinned
PR97 witness (`witness_23.json.gz`, SHA-256 {wsha}). Data are untrusted until the accompanying
kernel checks pass. -/

@[expose] public section

namespace IntegerMultBounds.MathlibTM2.M8.Local
'''
FOOTER = '\nend IntegerMultBounds.MathlibTM2.M8.Local\n'


def tree_text(vals):
    if len(vals) == 1:
        return '.leaf %s' % vals[0]
    mid = len(vals) // 2
    return '.node (%s) (%s)' % (tree_text(vals[:mid]), tree_text(vals[mid:]))


def top(ns):
    if len(ns) == 1:
        return ns[0]
    mid = len(ns) // 2
    return '.node (%s) (%s)' % (top(ns[:mid]), top(ns[mid:]))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text)


def lean_use(u):
    if u[0] == 'gate':
        return '.gate %d %s' % (u[1], 'true' if u[2] else 'false')
    return '.root %d' % u[1]


def lean_uses(us):
    return '[%s]' % ', '.join(lean_use(u) for u in us)


def list_defs(name, doc, us, piece=128):
    """a long list of uses as pieces of `piece` entries joined by a balanced tree of appends"""
    parts = [us[i:i + piece] for i in range(0, len(us), piece)] or [[]]
    text = ''
    names = []
    for i, part in enumerate(parts):
        names.append('%s_%02d' % (name, i))
        text += 'def %s : List Use :=\n  %s\n\n' % (names[-1], lean_uses(part))

    def join(ns):
        if len(ns) == 1:
            return ns[0]
        mid = len(ns) // 2
        return '(%s ++ %s)' % (join(ns[:mid]), join(ns[mid:]))

    text += '%sdef %s : List Use :=\n  %s\n\n' % (doc, name, join(names))
    return text


def main(pr97_dir, data_path, lean_root=None):
    Wraw = sd.read(pr97_dir, 'witness_23.json.gz')
    Draw = sd.read(pr97_dir, 'deferred_23.json.gz')
    wsha = sd.PINS['witness_23.json.gz']
    dsha = sd.PINS['deferred_23.json.gz']
    S = sd.Schedule(Wraw, Draw)
    data = json.load(open(data_path))
    assert data['source']['sha256'] == wsha
    N, v = data['N'], data['v']
    nodes = data['nodes']
    trip = list(combinations(range(H), 3))
    tid = {T: i for i, T in enumerate(trip)}

    # roots in the canonical order of emit_lean.py
    roots = [None] * (3 * v + H)
    for q in data['roots']:
        if 'out' in q:
            c, T = q['out']
            roots[3 * tid[tuple(T)] + T.index(c)] = q
        else:
            roots[3 * v + q['ret']] = q
    root_index = {}
    for j, q in enumerate(roots):
        root_index[('out', q['out'][0], tuple(q['out'][1])) if 'out' in q else ('ret', q['ret'])] = j

    # old ids -> new ids, the witness's use lists (as in witness.py)
    args_old = {int(n): (tuple(a) if a else None) for n, a in Wraw['args'].items()}
    dim = {}
    rows = [[int(q in T) for q in range(H)] for T in trip]
    sup = {}
    for n in sorted(args_old):
        a = args_old[n]
        sup[n] = (1 << (n - 1)) if a is None else sup[a[0]] | sup[a[1]]
    for n in sorted(args_old):
        dim[n] = wit.rank_mod([rows[i] for i in range(len(trip)) if sup[n] >> i & 1])
    order_old = sorted(args_old, key=lambda n: (dim[n], n))
    new = {n: i for i, n in enumerate(order_old)}
    users = {n: [] for n in args_old}
    for n in order_old:
        a = args_old[n]
        if a:
            for pos, x in enumerate(a):
                users[x].append(('gate', n, pos))
    for c, T, n in sorted((c, tuple(T), n) for c, T, n in Wraw['outputs']):
        users[n].append(('out', (c, T)))
    for c, n in sorted((c, n) for c, n in Wraw['retained']):
        users[n].append(('ret', c))

    def lu(u):
        if u[0] == 'gate':
            return ('gate', new[u[1]], u[2] == 1)
        if u[0] == 'out':
            return ('root', root_index[('out', u[1][0], tuple(u[1][1]))])
        return ('root', root_index[('ret', u[1])])

    def arg(n, pos):
        r = nodes[n]
        return (r['args'][1] if pos else r['args'][0]) if 'args' in r else 0

    def link(n):
        L = nodes[n].get('link')
        return (L['operand'] == 1, L['user'], L['pos'] == 1) if L else None

    linked = set()
    for n in range(N):
        L = link(n)
        if L:
            linked.add(('gate', L[1], L[2]))
    gate_uses = defaultdict(list)
    for t in range(v, N):
        for pos in (False, True):
            gate_uses[arg(t, pos)].append(('gate', t, pos))
    root_uses = defaultdict(list)
    for j, q in enumerate(roots):
        root_uses[q['node']].append(('root', j))

    def default_free(y):
        return [u for u in gate_uses[y] + root_uses[y] if u not in linked]

    # the serving orders: the kept use, then the copies by starting dimension
    late = {int(n): (e, l) for n, (e, l) in Wraw['late'].items()}
    head = {new[o]: lu(users[o][l[-1]]) for o, (e, l) in late.items()}

    def start_use(s):
        st = Draw['start'][s]
        return lu(users[st[1]][st[2]])

    ops_up = [tuple(o[:2]) + (tuple(o[2]),) if o[0] == 'fan' else tuple(o) for o in Draw['ops']]
    held = {}
    orders = {}
    fan_index = {}
    for i, op in enumerate(ops_up):
        if op[0] == 'src':
            held[op[1]] = op[2]
        elif op[0] == 'add':
            held[op[1]] = op[3]
        else:
            n = held[op[1]]
            for f in op[2]:
                held[f] = n
            y = new[n]
            fan_index[y] = i
            if y < v:
                continue
            tg = sorted(op[2], key=S.start_dim)
            orders[y] = [head.get(y, default_free(y)[0])] + [start_use(s) for s in tg]
    for y, h in head.items():
        orders.setdefault(y, [h])

    def rank(y, u):
        o = orders.get(y)
        if o is None:
            return 0
        return o.index(u) if u in o else len(o)

    def free_uses(y):
        us = sorted(gate_uses[y] + root_uses[y], key=lambda u: rank(y, u))
        return [u for u in us if u not in linked]

    # Dag.compile with the serving orders
    nxt = 0
    pend = {}
    ops = []
    creat = {}

    def serve(node, piv, us):
        nonlocal nxt
        if not us:
            return
        pend[us[0]] = piv
        for u in us[1:]:
            pend[u] = nxt
            creat[nxt] = u
            ops.append(('copy', piv, nxt, node))
            nxt += 1

    for n in range(N):
        if n < v:
            s = nxt
            nxt += 1
            ops.append(('src', s, n))
            us = free_uses(n)
            creat[s] = us[0]
            serve(n, s, us)
        else:
            sa = pend.get(('gate', n, False), 0)
            sb = pend.get(('gate', n, True), 0)
            L = link(n)
            if L:
                o, t, pos = L
                piv, oth = (sa, sb) if o else (sb, sa)
                ops.append(('add', piv, oth, n))
                pend[('gate', t, pos)] = oth
                serve(n, piv, free_uses(n))
            else:
                ops.append(('add', sa, sb, n))
                serve(n, sa, free_uses(n))
    R = nxt
    assert R == Draw['R']

    # upstream slot -> compiled slot, by the use each was created for; equal histories
    slot_of = {u: s for s, u in creat.items()}
    hist = defaultdict(list)
    for op in ops:
        for s in ([op[1]] if op[0] == 'src' else [op[1], op[2]]):
            nd = op[2] if op[0] == 'src' else op[3]
            if not hist[s] or hist[s][-1] != nd:
                hist[s].append(nd)
    up2lean = {}
    for s, st in enumerate(Draw['start']):
        u = free_uses(new[st[1]])[0] if st[0] == 'src' else start_use(s)
        up2lean[s] = slot_of[u]
        assert [new[n] for n in Draw['hold'][s]] == hist[up2lean[s]], ('history', s)
    assert len(set(up2lean.values())) == R

    # phases: upstream's phase one
    prev, pred, last = {}, defaultdict(list), {}
    for i, op in enumerate(ops_up):
        for s in (([op[1], op[2]] if op[0] == 'add' else [op[1]] + list(op[2]))
                  if op[0] != 'src' else []):
            if s in prev:
                pred[i].append(prev[s])
            prev[s] = i
            last[s] = i
    ret_slots = [s for s, c in Draw['ret']]
    ph = set()
    stack = [last[s] for s in ret_slots]
    while stack:
        i = stack.pop()
        if i not in ph:
            ph.add(i)
            stack.extend(pred[i])
    Phi = [False] * N
    Psi = [False] * N
    held = {}
    fan_ph = {}
    for i, op in enumerate(ops_up):
        if op[0] == 'src':
            held[op[1]] = op[2]
        elif op[0] == 'add':
            held[op[1]] = op[3]
            Phi[new[op[3]]] = i in ph
        else:
            n = held[op[1]]
            for f in op[2]:
                held[f] = n
            fan_ph[new[n]] = i in ph
    for y in range(v, N):
        Psi[y] = fan_ph.get(y, Phi[y])
    cen = lambda j: j >= 3 * v

    def use_node(u):
        return arg(u[1], u[2]) if u[0] == 'gate' else roots[u[1]]['node']

    def need(u):
        return Phi[u[1]] if u[0] == 'gate' else cen(u[1])

    # the local phase conditions (PhaseHyp)
    donor = {(L[1], L[2]): n for n in range(N) for L in [link(n)] if L}
    for n in range(N):
        assert not Psi[n] or Phi[n]
    for t in range(v, N):
        if Phi[t]:
            for pos in (False, True):
                assert arg(t, pos) < v or Psi[arg(t, pos)]
    for (t, pos), n in donor.items():
        assert not Phi[t] or Phi[n]
    for j in range(3 * v, len(roots)):
        assert roots[j]['node'] >= v and Psi[roots[j]['node']]
    dl = [creat[up2lean[s]] for s in Draw['readout_order']]
    for u in dl:
        y = use_node(u)
        assert u in free_uses(y)
        if y >= v:
            assert not Psi[y] and free_uses(y)[0] != u and orders[y][0] == free_uses(y)[0]
        else:
            assert not need(u)
    sel = set(Draw['readout_order'])
    vl = [creat[up2lean[s]] for s in Draw['deferred_v_order']]
    srcop = {o[1]: o[2] for o in Draw['ops'] if o[0] == 'src'}
    early = sorted((s for s in srcop if s not in sel), key=lambda s: (srcop[s], S.vdim[s], s))
    ve = [creat[up2lean[s]] for s in early]

    # the word's conditions and an F2 replay
    vops = [('src', op[2], op[3]) if op[0] == 'copy' and op[3] < v else op for op in ops]
    slots = lambda op: [op[1]] if op[0] == 'src' else [op[1], op[2]]
    phase = lambda op: Phi[op[3]] if op[0] == 'add' else Psi[op[3]]
    side = [op for op in vops if op[0] != 'src']
    srcs = [op for op in vops if op[0] == 'src']
    defS = [pend[u] for u in dl]
    dset = set(defS)
    assert len(dset) == len(defS)
    first = [op for op in side if phase(op)]
    rest = [op for op in side if not phase(op)]
    cslots = {pend[('root', j)] for j in range(3 * v, len(roots))}
    assert not any(s in dset for op in first for s in slots(op))
    assert not any(s in cslots for op in rest for s in slots(op))
    assert not cslots & dset
    low = set()
    for op in side:
        if phase(op):
            assert not any(s in low for s in slots(op))
        else:
            low.update(slots(op))

    def targets(j):
        return [j // 3] if j < 3 * v else [t for t in range(v) if j - 3 * v in trip[t]]

    cov = [0] * R
    for j in range(len(roots)):
        for T in targets(j):
            cov[pend[('root', j)]] ^= 1 << T
    for op in reversed(side):
        if op[0] == 'add':
            cov[op[2]] ^= cov[op[1]]
        else:
            cov[op[1]] ^= cov[op[2]]

    def gate(op):
        if op[0] == 'src':
            return (('aux', op[1]), ('x', op[2]))
        if op[0] == 'add':
            return (('aux', op[1]), ('aux', op[2]))
        return (('aux', op[2]), ('aux', op[1]))

    def rd(ss):
        return [(('y', T), ('aux', s)) for s in ss for T in range(v) if cov[s] >> T & 1]

    def reads(js):
        return [(('y', T), ('aux', pend[('root', j)])) for j in js for T in targets(j)]

    vnow = [op for op in srcs if op[1] not in dset]
    vlate = [op for op in srcs if op[1] in dset]
    word = (rd([s for s in range(R) if s not in dset]) + [gate(o) for o in vnow] +
            [gate(o) for o in first] + reads(range(3 * v, len(roots))) + rd(defS) +
            [gate(o) for o in vlate] + [gate(o) for o in rest] + reads(range(3 * v)) +
            [gate(o) for o in reversed(vnow + vlate + first + rest)])
    rng = random.Random(97)
    for _ in range(3):
        st = {('x', T): rng.getrandbits(1) for T in range(v)}
        st.update({('y', T): rng.getrandbits(1) for T in range(v)})
        st.update({('aux', s): rng.getrandbits(1) for s in range(R)})
        init = dict(st)
        for d, s in word:
            st[d] ^= st[s]
        assert all(st[('y', T)] == init[('y', T)] ^ init[('x', T)] for T in range(v))
        assert all(st[k] == init[k] for k in st if k[0] != 'y')

    if lean_root is None:
        # Reuse this compiler and its history checks when attaching frame data.
        return dict(nodeMap=sorted(new.items()), slotMap=sorted(up2lean.items()),
                    ops=vops, side=side, rootSlots=[pend[('root', j)] for j in range(len(roots))],
                    deferred=defS,
                    earlySources=[pend[u] for u in ve], lateSources=[pend[u] for u in vl],
                    first=first, rest=rest)

    # emit
    base = os.path.join(lean_root, 'IntegerMultBounds', 'MathlibTM2', 'M8', 'Local')
    vals = []
    for n in range(WIDTH):
        if n < N:
            bits = int(Phi[n]) + 2 * int(Psi[n])
            vals.append('(%d, %s)' % (bits, lean_uses(orders.get(n, []))))
        else:
            vals.append('(0, [])')
    for kk in range(16):
        subs = []
        text = HEADER.format(imports='public import IntegerMultBounds.MathlibTM2.M8.Local.TreeFacts\npublic import IntegerMultBounds.MathlibTM2.M8.Local.Compile',
                             dsha=dsha, wsha=wsha)
        for i in range(SUB // LEAFS):
            name = 'bdata%02d_%02d' % (kk, i)
            text += 'def %s : Tree (Nat × List Use) :=\n  %s\n\n' % (
                name, tree_text(vals[SUB * kk + LEAFS * i:SUB * kk + LEAFS * (i + 1)]))
            subs.append(name)
        text += 'def bdata%02d : Tree (Nat × List Use) := %s\n\n' % (kk, top(subs))
        text += ('theorem bdata%02d_perfect : bdata%02d.Perfect 4096 :=\n'
                 '  Tree.perfect_of_perfectB _ _ (by decide +kernel)\n') % (kk, kk)
        write(os.path.join(base, 'DataB', 'BData%02d.lean' % kk), text + FOOTER)
    imports = '\n'.join('public import IntegerMultBounds.MathlibTM2.M8.Local.DataB.BData%02d' % kk
                        for kk in range(16))
    text = HEADER.format(imports=imports, dsha=dsha, wsha=wsha)
    text += ('/-- The phase bits and serving order of every node (width 65536). -/\n'
             'def bdata : Tree (Nat × List Use) := %s\n\n') % top(['(bdata%02d)' % kk for kk in range(16)])
    for kk in range(16):
        text += ('theorem bdata_get_%02d (i : ℕ) (hi : i < 4096) :\n'
                 '    bdata.get 65536 (4096 * %d + i) = bdata%02d.get 4096 i := by\n'
                 '  unfold bdata\n'
                 '  simp only [Tree.get_node]\n'
                 '  split_ifs <;> first | (exfalso; omega) | exact Tree.get_congr (by norm_num) (by omega)\n\n'
                 ) % (kk, kk, kk)
    chunks = [dl[i:i + DCHUNK] for i in range(0, len(dl), DCHUNK)]
    for i, ch in enumerate(chunks):
        text += list_defs('deferred%d' % i, '', ch)
    text += ('/-- The deferred uses, in readout order. -/\ndef deferredUses : List Use :=\n  %s\n\n'
             % ' ++ '.join('deferred%d' % i for i in range(len(chunks))))
    text += list_defs('earlyV', '/-- The uses of the early V gates, in order. -/\n', ve)
    text += list_defs('lateV', '/-- The uses of the deferred V gates, in order. -/\n', vl)
    write(os.path.join(base, 'DataB', 'BData.lean'), text + FOOTER)

    imports = ('public import IntegerMultBounds.MathlibTM2.M8.Local.KernelB')
    for kk in range(16):
        text = HEADER.format(imports=imports, dsha=dsha, wsha=wsha)
        text += ('theorem bnodes%02d :\n'
                 '    Tree.all bnodeOk (fun x => Nat.beq x.1 0) nodeCount bdata%02d (4096 * %d) 4096 = true := by\n'
                 '  decide +kernel\n') % (kk, kk, kk)
        write(os.path.join(base, 'ChecksB', 'Nodes%02d.lean' % kk), text + FOOTER)
    text = HEADER.format(imports=imports, dsha=dsha, wsha=wsha)
    for i in range(len(chunks)):
        text += ('theorem deferredOk%d : deferred%d.all deferredOk = true := by\n'
                 '  decide +kernel\n\n') % (i, i)
    text += 'theorem centresOk : (List.range\' (3 * leafCount) 23).all centreOk = true := by\n  decide +kernel\n'
    write(os.path.join(base, 'ChecksB', 'Deferred.lean'), text + FOOTER)
    print(json.dumps(dict(R=R, ops=len(ops), first=len(first), rest=len(rest), deferred=len(dl),
                          early_v=len(ve), late_v=len(vl), orders=len(orders),
                          phase_add=sum(Phi), phase_copy=sum(Psi), word=len(word),
                          chunks=len(chunks))))


if __name__ == '__main__':
    main(*sys.argv[1:4])
