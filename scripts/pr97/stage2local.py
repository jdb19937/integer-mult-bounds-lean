#!/usr/bin/env python3
"""Emit the rank table and the local-step checks of the PR97 side slots (stdlib only).

Usage: stage2local.py DATA_JSON HIST_JSON LEAN_ROOT

DATA_JSON is generate.py's output (the data of `M8/Local/Data`), HIST_JSON stage2hist.py's.
Writes, under LEAN_ROOT/IntegerMultBounds/MathlibTM2/M8/Local/:
* Data/DimsKK.lean and Data/Dims.lean: the rank of every node frame, a tree of width 65536;
* Checks/RankKK.lean: each entry is the rank of the node's pair mask (`rankOk`), checked per
  subtree of 256 nodes;
* Checks/StepsKK.lean, Checks/RootSteps.lean: the counts by code of the moves of the nodes of
  each subtree (`nodeFS`) and of the roots (`rootFS`), a move of rank r coded r when counted
  positively and 24 + r when negatively;
* Checks/StepsAll.lean: the counts of all nodes, and the local steps by rank.
The script replays `LocalSteps.nodeFS` and `rootFS` and checks that the counts, with one move of
rank 23 per slot, are the local steps of stage2hist.py.
"""
import json
import os
import sys
from collections import Counter

import stage2hist as h

sys.set_int_max_str_digits(0)

WIDTH = 65536
SUB = 4096
LEAFS = 256
H = 23

HEADER = '''module

{imports}

/-! Generated by `scripts/pr97/stage2local.py` from `scripts/pr97/generate.py`'s output for the
pinned PR97 witness (`witness_23.json.gz`, SHA-256 {sha}). Data are untrusted until the
accompanying kernel checks pass. -/

@[expose] public section

namespace IntegerMultBounds.MathlibTM2.M8.Local
'''
FOOTER = '\nend IntegerMultBounds.MathlibTM2.M8.Local\n'


def tree_text(vals):
    if len(vals) == 1:
        return '.leaf %s' % vals[0]
    mid = len(vals) // 2
    return '.node (%s) (%s)' % (tree_text(vals[:mid]), tree_text(vals[mid:]))


def top(ns):
    if len(ns) == 1:
        return ns[0]
    mid = len(ns) // 2
    return '.node (%s) (%s)' % (top(ns[:mid]), top(ns[mid:]))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text)


def lean_int(c):
    return '%d' % c if c >= 0 else '(%d)' % c


def main(data_path, hist_path, lean_root):
    D, N, v, nodes, roots = h.load(data_path)
    sha = D['source']['sha256']
    cache = {}
    dim = [h.frame_rank(h.supp_triples(nodes[n]['supp']), cache) for n in range(N)]
    R = h.compile_lean(N, v, nodes, roots)[0]
    dims = dim + [0] * (WIDTH - N)

    def args(n):
        return nodes[n]['args'] if 'args' in nodes[n] else (0, 0)

    def donor(n, pos):
        lf = nodes[n].get('linkedFrom', {})
        key = '1' if pos else '0'
        return lf[key] if key in lf else None

    def sub(a, b):
        return max(a - b, 0)

    def free_fs(d):
        return [(d, 1), (sub(H, d), 1), (H, -1)]

    def node_fs(k):
        if 'args' not in nodes[k]:
            return []
        a, b = args(k)
        da = dims[donor(k, False) if donor(k, False) is not None else a]
        db = dims[donor(k, True) if donor(k, True) is not None else b]
        dk = dims[k]
        out = [(sub(dk, da), 1), (sub(H, dk), 1), (sub(H, da), -1), (sub(dk, db), 1),
               (sub(H, dk), 1), (sub(H, db), -1), (dk, -1), (sub(H, dk), -1), (H, 1)]
        if donor(k, False) is None:
            out += free_fs(dims[a])
        if donor(k, True) is None:
            out += free_fs(dims[b])
        return out

    nout = 3 * v
    def root_fs(j):
        dq = dims[roots[j]['node']]
        rk = 22 if j < nout else dq
        return free_fs(dq) + [(sub(rk, dq), 1), (sub(H, rk), 1), (sub(H, dq), -1)]

    def hist(fs):
        c = [0] * 24
        for r, x in fs:
            assert r < 24
            c[r] += x
        return c

    chunk_hists = []
    for kk in range(16):
        fs = []
        for k in range(SUB * kk, SUB * (kk + 1)):
            if k < N:
                fs += node_fs(k)
        chunk_hists.append(hist(fs))
    root_hist = hist([e for j in range(len(roots)) for e in root_fs(j)])
    total = [sum(c[i] for c in chunk_hists) + root_hist[i] for i in range(24)]
    total[H] += R
    local = dict(json.load(open(hist_path))['localSteps'])
    assert {i: total[i] for i in range(1, 24) if total[i]} == {int(r): c for r, c in local.items()}, total

    base = os.path.join(lean_root, 'IntegerMultBounds', 'MathlibTM2', 'M8', 'Local')
    for kk in range(16):
        vals = ['%d' % x for x in dims[SUB * kk:SUB * (kk + 1)]]
        subs = []
        text = HEADER.format(imports='public import IntegerMultBounds.MathlibTM2.M8.Local.Kernel', sha=sha)
        for i in range(SUB // LEAFS):
            name = 'dims%02d_%02d' % (kk, i)
            text += 'def %s : Tree Nat :=\n  %s\n\n' % (name, tree_text(vals[LEAFS * i:LEAFS * (i + 1)]))
            subs.append(name)
        text += 'def dims%02d : Tree Nat := %s\n' % (kk, top(subs))
        write(os.path.join(base, 'Data', 'Dims%02d.lean' % kk), text + FOOTER)
    imports = '\n'.join('public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Dims%02d' % kk
                        for kk in range(16))
    text = HEADER.format(imports=imports, sha=sha)
    text += '/-- The ranks of the node frames (width 65536). -/\ndef dims : Tree Nat := %s\n' % top(
        ['(dims%02d)' % kk for kk in range(16)])
    write(os.path.join(base, 'Data', 'Dims.lean'), text + FOOTER)

    def codes(fs):
        out = []
        for r, x in fs:
            assert 0 <= r < 24 and x in (1, -1)
            out.append(r if x == 1 else 24 + r)
        return out

    def count(cs):
        c = [0] * 48
        for e in cs:
            c[e] += 1
        return c

    def lean_list(c):
        return '[%s]' % ', '.join('%d' % x for x in c)

    chunk_counts = []
    for kk in range(16):
        imports = '\n'.join([
            'public import IntegerMultBounds.MathlibTM2.M8.Local.LocalSteps',
            'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Rec%02d' % kk,
            'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Dims'])
        text = HEADER.format(imports=imports, sha=sha)
        names = []
        for i in range(SUB // LEAFS):
            name = 'rank%02d_%02d' % (kk, i)
            names.append(name)
            text += ('theorem %s :\n    Tree.all (rankOk dims) (fun _ => true) nodeCount rec%02d_%02d %d %d = true := by\n'
                     '  decide +kernel\n\n') % (name, kk, i, SUB * kk + LEAFS * i, LEAFS)
        text += ('/-- Every node of subtree %d has the rank of its table entry. -/\n'
                 'theorem rank%02d :\n    Tree.all (rankOk dims) (fun _ => true) nodeCount rec%02d (4096 * %d) 4096 = true := by\n'
                 '  unfold rec%02d\n'
                 '  simp only [Tree.all_node, Nat.reduceMul, Nat.reduceAdd, Nat.reduceDiv, %s, Bool.and_self]\n'
                 ) % (kk, kk, kk, kk, kk, ', '.join(names))
        write(os.path.join(base, 'Checks', 'Rank%02d.lean' % kk), text + FOOTER)
        imports = '\n'.join([
            'public import IntegerMultBounds.MathlibTM2.M8.Local.LocalSteps',
            'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Rec%02d' % kk,
            'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Dims'])
        text = HEADER.format(imports=imports, sha=sha)
        cs = []
        for k in range(SUB * kk, min(SUB * (kk + 1), N)):
            cs += codes(node_fs(k))
        chunk_counts.append(count(cs))
        text += ('/-- The moves of the nodes of subtree %d, by code. -/\n'
                 'theorem steps%02d : Tree.hist (nodeFS dims) nodeCount rec%02d %d 4096 =\n'
                 '    %s := by\n  decide +kernel\n') % (kk, kk, kk, SUB * kk, lean_list(count(cs)))
        write(os.path.join(base, 'Checks', 'Steps%02d.lean' % kk), text + FOOTER)
    imports = '\n'.join([
        'public import IntegerMultBounds.MathlibTM2.M8.Local.LocalSteps',
        'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Roots',
        'public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Dims'])
    text = HEADER.format(imports=imports, sha=sha)
    cs = [e for j in range(len(roots)) for e in codes(root_fs(j))]
    root_counts = count(cs)
    text += ('/-- The moves of the roots, by code. -/\n'
             'def rootHist : List Nat := %s\n\n'
             'theorem rootSteps : Tree.hist (rootFS dims) rootCount roots 0 rootWidth = rootHist := by\n'
             '  decide +kernel\n') % lean_list(root_counts)
    write(os.path.join(base, 'Checks', 'RootSteps.lean'), text + FOOTER)
    node_total = [sum(c[i] for c in chunk_counts) for i in range(48)]
    signed = [node_total[r] - node_total[24 + r] + root_counts[r] - root_counts[24 + r] for r in range(24)]
    signed[H] += R
    assert signed == total, (signed, total)
    imports = '\n'.join(['public import IntegerMultBounds.MathlibTM2.M8.Local.Data.Records',
                         'public import IntegerMultBounds.MathlibTM2.M8.Local.Checks.RootSteps'] +
                        ['public import IntegerMultBounds.MathlibTM2.M8.Local.Checks.Steps%02d' % kk
                         for kk in range(16)])
    text = HEADER.format(imports=imports, sha=sha)
    text += ('/-- The moves of all nodes, by code. -/\n'
             'def nodeHist : List Nat := %s\n\n'
             'theorem nodeSteps : Tree.hist (nodeFS dims) nodeCount records 0 65536 = nodeHist := by\n'
             '  unfold records\n'
             '  simp only [Tree.hist_node, Nat.reduceDiv, Nat.reduceAdd, %s]\n'
             '  decide +kernel\n\n'
             '/-- The local steps of the side slots by rank, with one final move of rank 23 per slot\n'
             '(`stage2hist.py`\'s `localSteps`, with the moves of rank 0). -/\n'
             'def localSteps : List Int := [%s]\n\n'
             'theorem localSteps_eq : (List.range 24).all (fun r =>\n'
             '    (((nodeHist.getD r 0 : Nat) : Int) - (nodeHist.getD (24 + r) 0 : Nat) + (rootHist.getD r 0 : Nat) -\n'
             '      (rootHist.getD (24 + r) 0 : Nat) + (bif Nat.beq r 23 then %d else 0)) == localSteps.getD r 0) = true := by\n'
             '  decide +kernel\n') % (
        lean_list(node_total), ', '.join('steps%02d' % kk for kk in range(16)),
        ', '.join(lean_int(c) for c in total), R)
    write(os.path.join(base, 'Checks', 'StepsAll.lean'), text + FOOTER)
    print('slots', R, 'total', total)


if __name__ == '__main__':
    main(*sys.argv[1:])
