def emit_source_checks(result, compiled, destination):
    """Check the existing source-use lists before materializing their compiler slots."""
    assert result['source']['upstream'] == stage2designb.UPSTREAM
    assert result['source']['sha256'] == stage2designb.PINS
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Local'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Local'
    source_slots = {name: compiled[name] for name in ['earlySources', 'lateSources']}
    digest = hashlib.sha256(json.dumps(source_slots, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    opening = (f'/-! Generated by scripts/pr97/designbgeometry.py from upstream {stage2designb.UPSTREAM}.\n'
               f'Canonical source-key SHA-256 {digest}.\n'
               f'Witness {stage2designb.PINS["witness_23.json.gz"]};\n'
               f'schedule {stage2designb.PINS["deferred_23.json.gz"]}.\n'
               'Checks reuse the existing source-use lists; no compiler prefix is evaluated. -/\n'
               f'@[expose] public section\nnamespace {prefix}\n')

    def write(path, imports, body):
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text('module\n\n' + '\n'.join('public import ' + m for m in imports)
                          + '\n\n' + opening + '\n\n'.join(body) + f'\nend {prefix}\n')

    imports, aggregates = [], []
    for phase, field in [('earlyV', 'earlySources'), ('lateV', 'lateSources')]:
        count = (len(compiled[field]) + designbword.LEAFS - 1) // designbword.LEAFS
        facts = []
        for k in range((count + 7) // 8):
            name = f'SourceUses{phase[0].upper()}{k:02d}'
            imports.append(prefix + '.ChecksB.' + name)
            body = []
            for j in range(8 * k, min(count, 8 * (k + 1))):
                part = f'{phase}_{j:02d}'
                fact = part + '_sourceUseOk'
                facts.append(fact)
                body.append(f'theorem {fact} : {part}.all sourceUseOk = true := by\n'
                            '  unfold sourceUseOk\n  decide +kernel')
            write(f'ChecksB/{name}.lean', [prefix + '.UseSlotsB'], body)
        aggregates.append(f'theorem {phase}_sourceUseOk : {phase}.all sourceUseOk = true := by\n'
                          f'  simp only [{phase}, List.all_append, '
                          + ', '.join(facts) + ', Bool.true_and]')
    write('SourceUseChecksB.lean', imports, aggregates)
    print(f'{sum(len(v) for v in source_slots.values())} source uses reuse checked local records')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('snapshot', type=Path)
    parser.add_argument('--lean-root', type=Path, required=True)
    parser.add_argument('--compiled', type=Path)
    parser.add_argument('--dag-json', type=Path)
    parser.add_argument('--pr97-dir', type=Path)
    args = parser.parse_args()
    result = json.loads(args.snapshot.read_text())
    emit_lookup(result, args.lean_root)
    if args.dag_json:
        compiled = (json.loads(args.compiled.read_text()) if args.compiled else
                    designbword.main(str(args.pr97_dir), str(args.dag_json)))
        emit_geometry(result, compiled, json.loads(args.dag_json.read_text()), args.lean_root)
        emit_slot_geometry(result, compiled, args.lean_root)
        emit_root_geometry(result, compiled, args.lean_root)
        emit_source_checks(result, compiled, args.lean_root)
        designbcovariance.emit(result, compiled, json.loads(args.dag_json.read_text()), args.lean_root)
        designbkeyorder.emit(result, compiled, args.lean_root)
        designbtargetgeometry.emit(result, compiled, json.loads(args.dag_json.read_text()), args.lean_root)
        designbtargetranks.emit(args.lean_root)
        designbslots.emit(compiled, json.loads(args.dag_json.read_text()), args.lean_root)
        designbauxcoverage.emit(args.lean_root)
        designbhist.emit(result, compiled, args.lean_root)
        designbsourcegeometry.emit(result, args.lean_root)
        designbsigmaranks.emit(result, args.lean_root)


if __name__ == '__main__':
    main()
