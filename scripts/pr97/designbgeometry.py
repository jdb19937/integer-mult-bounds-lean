def root_witnesses(result, compiled):
    """Use each compiler root slot's full-chain endpoint, never a plain-word slot."""
    from itertools import combinations
    slot = dict(compiled['slotMap'])
    chains = {slot[s]: (i, chain) for i, (kind, s, chain) in
              enumerate(result['fullChains']) if kind == 'slot'}
    triples = list(combinations(range(stage2designb.H), 3))
    codes = [a + 32 * b + 1024 * c for a, b, c in triples for _ in range(3)]
    codes += [32768 + c for c in range(stage2designb.H)]
    assert len(compiled['rootSlots']) == len(codes) == 5336
    witnesses = []
    for s, code in zip(compiled['rootSlots'], codes):
        i, chain = chains[s]
        # The final one frame follows the actual root complement.
        assert chain[-1] == [1, 0]
        kind, label = chain[-2]
        assert kind == 3 and code in result['records'][label]['basis'], (s, code)
        witnesses.append((i, label))
    return witnesses


