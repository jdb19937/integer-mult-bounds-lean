def emit_lookup(result, destination):
    assert result['source']['upstream'] == stage2designb.UPSTREAM
    assert result['source']['sha256'] == stage2designb.PINS
    count = len(result['fullChains'])
    chunks = (count + 63) // 64
    assert chunks <= 512
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Frames.SignedFull'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Frames/SignedFull'
    digest = hashlib.sha256(json.dumps(result['fullChains'], separators=(',', ':')).encode()).hexdigest()
    opening = (f'/-! Generated by scripts/pr97/designbgeometry.py from upstream {stage2designb.UPSTREAM}.\n'
               f'Canonical full-chain SHA-256 {digest}.\n'
               f'Witness {stage2designb.PINS["witness_23.json.gz"]};\n'
               f'schedule {stage2designb.PINS["deferred_23.json.gz"]}.\n'
               'This tree references the existing chain data and reuses their proofs. -/\n'
               '@[expose] public section\n'
               f'namespace {prefix}\nnoncomputable section\nopen Local\n')
    def write(name, imports, body):
        root.mkdir(parents=True, exist_ok=True)
        (root / name).write_text('module\n\n' + '\n'.join('public import ' + m for m in imports)
                                + '\n\n' + opening + '\n\n'.join(body) + f'\nend\nend {prefix}\n')
    data = []
    checks = ['theorem chains_nil_checked : Signed.chainsCheck bankEntry bankSize [] = true := rfl']
    for j in range(16):
        vals = [f'.leaf chains{i:03d}' if i < chunks else '.leaf []'
                for i in range(32 * j, 32 * (j + 1))]
        data.append(f'def chainTree{j:02d} : Tree (List (List Signed.Frame)) := {designbword.top(vals)}')
        facts = [f'chains{i:03d}_checked' for i in range(32 * j, min(chunks, 32 * (j + 1)))]
        checks.append(f'theorem chainTree{j:02d}_checked : ChainLookup.every '
                      f'(Signed.chainsCheck bankEntry bankSize) chainTree{j:02d} = true := by\n'
                      f'  simp only [chainTree{j:02d}, ChainLookup.every, '
                      + ', '.join(facts + (['chains_nil_checked'] if 32 * (j + 1) > chunks else [])) + ', Bool.true_and]')
    data += ['def chainTree : Tree (List (List Signed.Frame)) := '
             + designbword.top([f'chainTree{j:02d}' for j in range(16)]),
             'def chainAt (i : Nat) : List Signed.Frame :=\n'
             '  ((chainTree.get 512 (i / 64))[i % 64]?).getD []']
    write('LookupData.lean', [prefix + '.Chains',
          'IntegerMultBounds.MathlibTM2.M8.Frames.ChainLookup'], data)
    checks.append('theorem chainTree_checked : ChainLookup.every '
                  '(Signed.chainsCheck bankEntry bankSize) chainTree = true := by\n'
                  '  simp only [chainTree, ChainLookup.every, '
                  + ', '.join(f'chainTree{j:02d}_checked' for j in range(16)) + ', Bool.true_and]')
    checks.append('theorem chainAt_checked (i : Nat) : Signed.chainCheck bankEntry bankSize (chainAt i) = true := by\n'
                  '  exact ChainLookup.all_getD (Signed.chainCheck bankEntry bankSize) _\n'
                  '    (ChainLookup.every_get _ _ chainTree_checked 512 (i / 64)) [] rfl (i % 64)')
    write('LookupChecks.lean', [prefix + '.LookupData', prefix + '.ChainChecks'], checks)


def geometry_witnesses(result, compiled, dag):
    """Find existing chains that witness the compiler's incoming and copy edges."""
    slot, node = dict(compiled['slotMap']), dict(compiled['nodeMap'])
    node_labels = {node[n]: tuple(frame) for n, frame in result['nodeFrames']}
    starts = {slot[n]: tuple(chain[1]) for kind, n, chain in result['fullChains'] if kind == 'slot'}
    chain_index = {slot[n]: i for i, (kind, n, _) in enumerate(result['fullChains']) if kind == 'slot'}
    chains = [[tuple(f) for f in chain] for _, _, chain in result['fullChains']]
    orders = [[tuple(u) for u in us] for us in compiled['servingOrders']]
    counts = compiled['slotsBefore']
    donors = {}
    for n, r in enumerate(dag['nodes']):
        if 'link' in r:
            link = r['link']
            donors[link['user'], bool(link['pos'])] = n

    def free_label(n, u):
        i = orders[n].index(u)
        if n < dag['v']:
            return starts[counts[n] + i]
        if i:
            return starts[counts[n] + i - 1]
        return node_labels[n] if len(orders[n]) <= 1 else starts[counts[n] + len(orders[n]) - 2]

    def argument_label(n, pos):
        donor = donors.get((n, pos))
        return node_labels[donor] if donor is not None else free_label(dag['nodes'][n]['args'][pos], ('gate', n, pos))

    def edge(a, b, frames):
        if a == b:
            return True
        return any(a == x and b in frames[j + 1:] for j, x in enumerate(frames))

    current, witness = {}, [(0, 0, 0)] * dag['N']
    for op in compiled['ops']:
        if op[0] == 'src':
            _, p, n = op
            current[p] = starts[p]
        elif op[0] == 'copy':
            _, p, f, n = op
            current[p] = current[f] = starts[f]
        else:
            _, p, o, n = op
            link = dag['nodes'][n].get('link')
            left, right = (o, p) if link and not link['operand'] else (p, o)
            for pos, wire in [(False, left), (True, right)]:
                label = argument_label(n, pos)
                assert current[wire] == label, ('argument frame', n, pos)
                assert edge(label, node_labels[n], chains[chain_index[wire]]), ('incoming edge', n, pos)
            labels = [node_labels[n]] + [starts[s] for s in range(counts[n], counts[n] + len(orders[n]) - 1)]
            assert all(edge(a, b, chains[chain_index[p]]) for a, b in zip(labels, labels[1:])), ('copy chain', n)
            witness[n] = (chain_index[left], chain_index[right], chain_index[p])
            current[p] = current[o] = node_labels[n]
    return witness


def emit_geometry(result, compiled, dag, destination):
    witness = geometry_witnesses(result, compiled, dag)
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Frames.GeometryB'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Frames/GeometryB'
    digest = hashlib.sha256(json.dumps(witness, separators=(',', ':')).encode()).hexdigest()
    opening = (f'/-! Generated by scripts/pr97/designbgeometry.py from upstream {stage2designb.UPSTREAM}.\n'
               f'Canonical edge-witness SHA-256 {digest}.\n'
               f'Witness {stage2designb.PINS["witness_23.json.gz"]};\n'
               f'schedule {stage2designb.PINS["deferred_23.json.gz"]}.\n'
               'Entries only name existing checked chains; all local path claims are kernel checked. -/\n'
               f'@[expose] public section\nnamespace {prefix}\nopen Local\n')
    def write(path, imports, body):
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text('module\n\n' + '\n'.join('public import ' + m for m in imports)
                          + '\n\n' + opening + '\n\n'.join(body) + f'\nend {prefix}\n')
    values = ['(%d, %d, %d)' % w for w in witness] + ['(0, 0, 0)'] * (65536 - len(witness))
    for k in range(16):
        names, body = [], []
        for j in range(32):
            name = f'edges{k:02d}_{j:02d}'
            names.append(name)
            body.append(f'def {name} : Tree (Nat × Nat × Nat) :=\n  '
                        + designbword.tree_text(values[4096 * k + 128 * j:4096 * k + 128 * (j + 1)]))
        body.append(f'def edges{k:02d} : Tree (Nat × Nat × Nat) := ' + designbword.top(names))
        body.append(f'theorem edges{k:02d}_perfect : edges{k:02d}.Perfect 4096 :=\n'
                    '  Tree.perfect_of_perfectB _ _ (by decide +kernel)')
        write(f'Data/Edges{k:02d}.lean', ['IntegerMultBounds.MathlibTM2.M8.Local.TreeFacts'], body)
        checks, terms = [], []
        for j in range(4):
            expr = designbword.top(names[8 * j:8 * (j + 1)])
            term = f'Tree.all nodeOk (fun _ => true) nodeCount ({expr}) {4096 * k + 1024 * j} 1024'
            terms.append(term)
            checks.append(f'theorem edges{k:02d}_{j}_checked : {term} = true := by\n'
                          '  unfold nodeOk\n  decide +kernel')
        checks.append(f'theorem edges{k:02d}_checked : Tree.all nodeOk (fun _ => true) nodeCount '
                      f'edges{k:02d} (4096 * {k}) 4096 = true := by\n'
                      f'  change (({terms[0]} && {terms[1]}) && ({terms[2]} && {terms[3]})) = true\n'
                      + '  rw [' + ', '.join(f'edges{k:02d}_{j}_checked' for j in range(4)) + ']\n  rfl')
        write(f'Checks/Edges{k:02d}.lean', [prefix + '.Kernel', prefix + f'.Data.Edges{k:02d}'], checks)
    data = ['def edges : Tree (Nat × Nat × Nat) := '
            + designbword.top([f'edges{k:02d}' for k in range(16)])]
    for k in range(16):
        data.append(f'theorem edges_get_{k:02d} (i : Nat) (hi : i < 4096) :\n'
                    f'    edges.get 65536 (4096 * {k} + i) = edges{k:02d}.get 4096 i := by\n'
                    '  unfold edges\n  simp only [Tree.get_node]\n'
                    '  split_ifs <;> first | (exfalso; omega) | exact Tree.get_congr (by norm_num) (by omega)')
    write('Data.lean', [prefix + f'.Data.Edges{k:02d}' for k in range(16)], data)
    print(f'{len(witness) - dag["v"]} additions and their copy chains reuse existing geometry')


