#!/usr/bin/env python3
"""Count the actual signed geometry, using kernel-checked physical-slot lookups.

Reconstruct the signed snapshot with stage2framebank.py --multi-nodes --signed-output,
and the compiler JSON with designbword.py. Neither input is a trusted certificate.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

import stage2designb
import stage2cert


def balanced(xs, op):
    if len(xs) == 1:
        return xs[0]
    mid = len(xs) // 2
    return f'{op} ({balanced(xs[:mid], op)}) ({balanced(xs[mid:], op)})'


def emit(result, compiled, destination):
    assert result['source']['upstream'] == stage2designb.UPSTREAM
    assert result['source']['sha256'] == stage2designb.PINS
    assert len(result['fullChains']) == 32408
    slots = {new: old for old, new in compiled['slotMap']}
    assert set(slots) == set(range(28866))
    assert set(slots.values()) == set(range(28866))
    records = result['records']

    def rank(f):
        if f[0] == 0:
            return 0
        if f[0] == 1:
            return 23
        length = len(records[f[1]]['basis'])
        return length if f[0] == 2 else 23 - length

    def steps(i):
        fs = result['fullChains'][i][2]
        dims = list(map(rank, fs))
        assert all(a <= b for a, b in zip(dims, dims[1:]))
        return [b - a for a, b in zip(dims, dims[1:]) if a != b]

    aux = [steps(slots[s]) for s in range(28866)]
    sigma = [[rank(result['sigma'][slots[s]])] for s in range(28866)]
    target = [steps(28866 + t) for t in range(1771)]
    source = [steps(30637 + n) for n in range(1771)]
    digest = hashlib.sha256(json.dumps([aux, sigma, target, source], separators=(',', ':')).encode()).hexdigest()
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Frames.SignedHistogramB'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Frames/SignedHistogramB'
    header = (f'/-! Generated by scripts/pr97/designbhist.py; upstream {stage2designb.UPSTREAM}.\n'
              f'Pinned hashes {json.dumps(stage2designb.PINS, sort_keys=True)}.\n'
              f'Canonical physical-slot rank-step SHA-256 {digest}.\n'
              'Counts are untrusted until their kernel equalities pass. -/\n'
              '@[expose] public section\nnamespace ' + prefix + '\nnoncomputable section\nopen Local\n')

    def counts(moves):
        hist = Counter(r for fs in moves for r in fs)
        assert all(0 <= r < 24 for r in hist)
        return '[' + ', '.join(str(hist[r]) for r in range(48)) + ']'

    def write(name, imports, body):
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('module\n\n' + '\n'.join('public import ' + m for m in imports) + '\n\n' +
                        header + '\n\n'.join(body) + '\nend\nend ' + prefix + '\n')

    imports, totals = [], []
    for kind, moves, checker, namespace, table in [
            ('Aux', aux, 'chainMoves', 'GeometryB', 'slots'),
            ('Sigma', sigma, 'sigmaMoves', 'AssignmentB', 'sigma')]:
        piece_width = 64 if kind == 'Sigma' else 128
        piece_count = 4096 // piece_width
        for k in range(8):
            body, pieces = [], []
            for j in range(piece_count):
                start = 4096 * k + piece_width * j
                name = f'{kind.lower()}{k:02d}_{j:02d}'
                pieces.append(name)
                body.append(f'def {name} : List Nat := {counts(moves[start:start + piece_width])}')
                body.append(f'theorem {name}_checked : Tree.hist {checker} GeometryB.slotCount\n'
                            f'    {namespace}.{table}{k:02d}_{j:02d} {start} {piece_width} = {name} := by\n'
                            f'  unfold {checker}\n  decide +kernel')
            total = f'{kind.lower()}{k:02d}'
            body.append(f'def {total} : List Nat := {counts(moves[4096*k:4096*(k+1)])}')
            terms = [f'Tree.hist {checker} GeometryB.slotCount {namespace}.{table}{k:02d}_{j:02d} {4096*k+piece_width*j} {piece_width}'
                     for j in range(piece_count)]
            body.append(f'theorem {total}_checked : Tree.hist {checker} GeometryB.slotCount\n'
                        f'    {namespace}.{table}{k:02d} {4096*k} 4096 = {total} := by\n'
                        f'  change {balanced(terms, "addH")} = {total}\n'
                        '  rw [' + ', '.join(n + '_checked' for n in pieces) + ']\n  decide +kernel')
            module = f'Checks.{kind}{k:02d}'
            imports.append(prefix + '.' + module)
            totals.append(total)
            write(f'Checks/{kind}{k:02d}.lean', [prefix + '.Kernel'], body)
    for kind, moves, offset in [('Target', target, 28866), ('Source', source, 30637)]:
        body, pieces = [], []
        for j in range(14):
            start, count = 128 * j, min(128, 1771 - 128 * j)
            name = f'{kind.lower()}{j:02d}'
            pieces.append(name)
            body.append(f'def {name} : List Nat := {counts(moves[start:start + count])}')
            body.append(f'theorem {name}_checked : histOf ((List.range\' {offset+start} {count}).flatMap\n'
                        f'    (chainMoves 0)) = {name} := by\n  unfold chainMoves\n  decide +kernel')
        total = kind.lower() + 'Hist'
        body.append(f'def {total} : List Nat := {counts(moves)}')
        body.append(f'theorem {total}_sum : ' + balanced(pieces, 'addH') + f' = {total} := by decide +kernel')
        imports.append(prefix + '.Checks.' + kind)
        write(f'Checks/{kind}.lean', [prefix + '.Kernel'], body)
    imports.append('IntegerMultBounds.MathlibTM2.M8.Global.SignedHistogram')
    aggregates = []
    for kind, moves in [('aux', aux), ('sigma', sigma)]:
        name = kind + 'Hist'
        aggregates.append(f'def {name} : List Nat := {counts(moves)}')
        aggregates.append(f'theorem {name}_sum : ' + balanced([f'{kind}{k:02d}' for k in range(8)], 'addH') +
                          f' = {name} := by decide +kernel')
    for kind, checker, ns, table, whole in [
            ('aux', 'chainMoves', 'GeometryB', 'slots', 'slotTree'),
            ('sigma', 'sigmaMoves', 'AssignmentB', 'sigma', 'sigmaTable')]:
        terms = [f'Tree.hist {checker} GeometryB.slotCount {ns}.{table}{k:02d} {4096*k} 4096'
                 for k in range(8)]
        aggregates.append(f'theorem {kind}Hist_checked : Tree.hist {checker} GeometryB.slotCount\n'
                          f'    {ns}.{whole} 0 32768 = {kind}Hist := by\n'
                          f'  change {balanced(terms, "addH")} = {kind}Hist\n'
                          '  rw [' + ', '.join(f'{kind}{k:02d}_checked' for k in range(8)) + ']\n'
                          f'  exact {kind}Hist_sum')
    for kind, offset in [('target', 28866), ('source', 30637)]:
        def merge(chunks):
            if len(chunks) == 1:
                return chunks[0]
            mid = len(chunks) // 2
            start, a, left, lhs = merge(chunks[:mid])
            _, b, right, rhs = merge(chunks[mid:])
            name = f'{kind}Hist_{start}_{a+b}'
            expression = f'addH ({lhs}) ({rhs})'
            aggregates.append(f'theorem {name} : histOf ((List.range\' {start} {a+b}).flatMap (chainMoves 0)) =\n'
                              f'    {expression} := by\n'
                              f'  rw [← List.range\'_append_1 (s := {start}) (m := {a}) (n := {b}),\n'
                              f'    List.flatMap_append, Global.histOf_append, {left}, {right}]')
            return start, a+b, name, expression
        chunks = [(offset+128*j, min(128, 1771-128*j), f'{kind}{j:02d}_checked', f'{kind}{j:02d}')
                  for j in range(14)]
        _, _, fact, _ = merge(chunks)
        aggregates.append(f'theorem {kind}Hist_checked : histOf ((List.range\' {offset} 1771).flatMap (chainMoves 0)) =\n'
                          f'    {kind}Hist := {fact}.trans {kind}Hist_sum')
    write('Checked.lean', imports, aggregates)
    hist = Counter()
    for fs in aux + target + source:
        for r in fs:
            hist[r] += 2 * 1771
    for fs in sigma:
        hist[506 + fs[0]] += 2 * 1771
    hist[22] += 2 * 1771 * 23
    hist[484] += 2 * 1771**2
    hist[1] += 1771**2
    assert [[r, n] for r, n in sorted(hist.items())] == result['histogram']
    certificate = dict(result, W=108516254, m=529, rankMass=sum(r*n for r,n in hist.items()))
    stage2cert.emit(certificate, str(destination), '--designb', script_name='stage2framebank.py')
    print('emitted 18 signed histogram check modules;', digest, flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('signed_json', type=Path)
    parser.add_argument('compiled_json', type=Path)
    parser.add_argument('--lean-root', type=Path, required=True)
    args = parser.parse_args()
    emit(json.loads(args.signed_json.read_text()), json.loads(args.compiled_json.read_text()), args.lean_root)
