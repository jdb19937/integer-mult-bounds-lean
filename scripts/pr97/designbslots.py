#!/usr/bin/env python3
"""Emit a locally checked argument/root slot table for the pinned design-B compiler.

Reconstruct inputs with generate.py, then invoke this script with PR97_DIR DAG_JSON
--lean-root ROOT. --compiled may reuse a freshly reconstructed designbword.py JSON.
The table is untrusted: local allocation and link equations are checked in Lean.
"""
import argparse
import hashlib
import json
from pathlib import Path

import designbword
import stage2designb


def collect(compiled, dag):
    assert dag['source']['sha256'] == stage2designb.PINS['witness_23.json.gz']
    ncount, v = dag['N'], dag['v']
    adds = {op[3]: op[1:3] for op in compiled['ops'] if op[0] == 'add'}
    slots, arguments = {}, [(0, 0)] * ncount
    for n in range(ncount):
        count = compiled['slotsBefore'][n]
        link = dag['nodes'][n].get('link')
        if n < v:
            piv = count
        else:
            piv, other = adds[n]
            a, b = (other, piv) if link and not link['operand'] else (piv, other)
            assert (slots[('gate', n, False)], slots[('gate', n, True)]) == (a, b)
            arguments[n] = a, b
            if link:
                key = ('gate', link['user'], bool(link['pos']))
                assert key not in slots
                slots[key] = other
        for i, use in enumerate(compiled['servingOrders'][n]):
            key = tuple(use)
            assert key not in slots
            slots[key] = count + i if n < v else piv if i == 0 else count + i - 1
    roots = [slots['root', j] for j in range(len(dag['roots']))]
    assert roots == compiled['rootSlots']
    assert len(adds) == ncount - v
    return arguments, roots


def emit(compiled, dag, destination):
    arguments, roots = collect(compiled, dag)
    digest = hashlib.sha256(json.dumps([arguments, roots], separators=(',', ':')).encode()).hexdigest()
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Local.SlotAssignmentB'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Local/SlotAssignmentB'
    header = (f'/-! Generated by scripts/pr97/designbslots.py; upstream {stage2designb.UPSTREAM}.\n'
              f'Pinned hashes {json.dumps(stage2designb.PINS, sort_keys=True)}.\n'
              f'Canonical slot-assignment SHA-256 {digest}.\n'
              'The table is untrusted until its allocation/link checks pass. -/\n'
              '@[expose] public section\n'
              f'namespace {prefix}\nopen Local\nnoncomputable section\n')

    def write(name, imports, body):
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('module\n\n' + '\n'.join('public import ' + m for m in imports) + '\n\n' +
                        header + '\n\n'.join(body) + f'\nend\nend {prefix}\n')

    args = [f'({a}, {b})' for a, b in arguments] + ['(0, 0)'] * (65536 - len(arguments))
    imports, check_imports = [], []
    for k in range(16):
        name = f'Arguments{k:02d}'
        imports.append(prefix + '.Data.' + name)
        check_imports.append(prefix + '.Checks.' + name)
        names, data, checks = [], [], []
        for j in range(32):
            piece = f'arguments{k:02d}_{j:02d}'
            names.append(piece)
            start = 4096 * k + 128 * j
            data.append(f'def {piece} : Tree (Nat × Nat) :=\n  ' + designbword.tree_text(args[start:start + 128]))
            checks.append(f'theorem {piece}_checked : Tree.all nodeOk (fun _ => true) nodeCount\n'
                          f'    {piece} {start} 128 = true := by\n  unfold nodeOk\n  decide +kernel')
        data.append(f'def arguments{k:02d} : Tree (Nat × Nat) := ' + designbword.top(names))
        data.append(f'theorem arguments{k:02d}_perfect : arguments{k:02d}.Perfect 4096 :=\n'
                    '  Tree.perfect_of_perfectB _ _ (by decide +kernel)')
        def conjunction(xs):
            if len(xs) == 1:
                return xs[0]
            mid = len(xs) // 2
            return '(' + conjunction(xs[:mid]) + ' && ' + conjunction(xs[mid:]) + ')'
        expression = conjunction([f'Tree.all nodeOk (fun _ => true) nodeCount {piece} {4096 * k + 128 * j} 128' for j, piece in enumerate(names)])
        checks.append(f'theorem arguments{k:02d}_checked : Tree.all nodeOk (fun _ => true) nodeCount\n'
                      f'    arguments{k:02d} (4096 * {k}) 4096 = true := by\n'
                      f'  change {expression} = true\n'
                      '  rw [' +
                      ', '.join(n + '_checked' for n in names) + ']\n  decide')
        write('Data/' + name + '.lean', ['IntegerMultBounds.MathlibTM2.M8.Local.TreeFacts'], data)
        write('Checks/' + name + '.lean', [prefix + '.Kernel', prefix + '.Data.' + name], checks)
    rs = list(map(str, roots)) + ['0'] * (8192 - len(roots))
    for k in range(2):
        name = f'Roots{k:02d}'
        imports.append(prefix + '.Data.' + name)
        write('Data/' + name + '.lean', ['IntegerMultBounds.MathlibTM2.M8.Local.TreeFacts'], [
            f'def roots{k:02d} : Tree Nat :=\n  ' + designbword.tree_text(rs[4096 * k:4096 * (k + 1)]),
        ])
    data = ['def argumentSlots : Tree (Nat × Nat) := ' + designbword.top([f'arguments{k:02d}' for k in range(16)]),
            'def rootSlots : Tree Nat := .node roots00 roots01']
    for k in range(16):
        data.append(f'theorem argumentSlots_get_{k:02d} (i : Nat) (hi : i < 4096) :\n'
                    f'    argumentSlots.get 65536 (4096 * {k} + i) = arguments{k:02d}.get 4096 i := by\n'
                    '  unfold argumentSlots\n  simp only [Tree.get_node]\n'
                    '  split_ifs <;> first | (exfalso; omega) | exact Tree.get_congr (by norm_num) (by omega)')
    write('Data.lean', imports, data)
    facts = [
        'private theorem argumentChunk (k : Nat) (t : Tree (Nat × Nat)) (ht : t.Perfect 4096)\n'
        '    (hall : Tree.all nodeOk (fun _ => true) nodeCount t (4096 * k) 4096 = true)\n'
        '    (hget : ∀ i < 4096, argumentSlots.get 65536 (4096 * k + i) = t.get 4096 i)\n'
        '    (i : Nat) (hi : i < 4096) (hn : 4096 * k + i < nodeCount) :\n'
        '    nodeOk (4096 * k + i) (argumentSlots.get 65536 (4096 * k + i)) = true := by\n'
        '  rw [hget i hi]\n  exact Tree.all_get _ _ _ t 4096 (4096 * k) ht hall i hi hn',
        'theorem nodeOk_at (n : Nat) (hn : n < nodeCount) : nodeOk n (argument n) = true := by\n'
        '  change nodeOk n (argumentSlots.get 65536 n) = true\n'
        '  have hn\' : n < 64042 := hn\n'
        '  obtain ⟨k, i, hi, rfl⟩ : ∃ k i, i < 4096 ∧ n = 4096 * k + i :=\n'
        '    ⟨n / 4096, n % 4096, Nat.mod_lt _ (by norm_num), (Nat.div_add_mod n 4096).symm⟩\n'
        '  have hk : k < 16 := by omega\n  interval_cases k\n' +
        '\n'.join(f'  · exact argumentChunk {k} arguments{k:02d} arguments{k:02d}_perfect arguments{k:02d}_checked\n'
                  f'      argumentSlots_get_{k:02d} i hi hn' for k in range(16)),
    ]
    write('Checked.lean', ['Mathlib.Tactic.IntervalCases'] + check_imports, facts)
    print('slot assignments:', len(arguments), 'argument pairs,', len(roots), 'roots;', digest, flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('dag_json', type=Path)
    parser.add_argument('--compiled', type=Path)
    parser.add_argument('--lean-root', type=Path, required=True)
    a = parser.parse_args()
    dag = json.loads(a.dag_json.read_text())
    compiled = json.loads(a.compiled.read_text()) if a.compiled else designbword.main(str(a.source), str(a.dag_json))
    emit(compiled, dag, a.lean_root)
