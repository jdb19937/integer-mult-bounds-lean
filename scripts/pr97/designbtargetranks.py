#!/usr/bin/env python3
"""Check the ranks of existing target endpoints; no reconstructed input is needed.

The endpoint list and bank already record their pinned upstream provenance. This
emitter adds no data and evaluates only the length of each existing endpoint basis.
"""
import argparse
import json
from pathlib import Path

import stage2designb


def emit(destination):
    prefix = 'IntegerMultBounds.MathlibTM2.M8.Frames.TargetGeometryB'
    root = Path(destination) / 'IntegerMultBounds/MathlibTM2/M8/Frames/TargetGeometryB'
    header = (f'/-! Generated by scripts/pr97/designbtargetranks.py from the existing endpoint list and bank.\n'
              f'Upstream {stage2designb.UPSTREAM}; pinned hashes {json.dumps(stage2designb.PINS, sort_keys=True)}.\n'
              'No new bank records or endpoint data are introduced. -/\n'
              '@[expose] public section\n'
              f'namespace {prefix}\nnoncomputable section\n')

    def write(name, imports, body):
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('module\n\n' + '\n'.join('public import ' + m for m in imports)
                        + '\n\n' + header + '\n\n'.join(body) + f'\nend\nend {prefix}\n')

    write('EndpointRankKernel.lean', [prefix + '.Endpoints'], [
        '@[irreducible] def endpointRankOk (t : Nat) : Bool :=\n'
        '  (SignedFull.bankEntry (endpoint t)).basis.length == 1',
    ])
    ranges = []
    imports = []
    for group in range(4):
        name = f'EndpointRanks{group:02d}'
        imports.append(prefix + '.Checks.' + name)
        body = []
        for k in range(4 * group, min(4 * (group + 1), 14)):
            start, count = 128 * k, min(128, 1771 - 128 * k)
            fact = f'endpointRanks{k:02d}'
            ranges.append((start, count, fact))
            body.append(f'theorem {fact} : (List.range\' {start} {count}).all endpointRankOk = true := by\n'
                        '  unfold endpointRankOk\n  decide +kernel')
        write('Checks/' + name + '.lean', [prefix + '.EndpointRankKernel'], body)
    body = []
    while len(ranges) > 1:
        merged = []
        for i in range(0, len(ranges), 2):
            if i + 1 == len(ranges):
                merged.append(ranges[i])
                continue
            start, a, ha = ranges[i]
            _, b, hb = ranges[i + 1]
            fact = f'endpointRanks_{start}_{a + b}'
            body.append(f'theorem {fact} : (List.range\' {start} {a + b}).all endpointRankOk = true :=\n'
                        f'  all_range_merge endpointRankOk {start} {a} {b} {ha} {hb}')
            merged.append((start, a + b, fact))
        ranges = merged
    body.append('theorem endpoint_basis_length (t : Nat) (ht : t < 1771) :\n'
                '    (SignedFull.bankEntry (endpoint t)).basis.length = 1 := by\n'
                f'  have h := List.all_eq_true.mp {ranges[0][2]} t (by simp; omega)\n'
                '  unfold endpointRankOk at h\n  exact eq_of_beq h')
    write('EndpointRankChecked.lean', imports + [prefix + '.RangeFacts'], body)
    print('target endpoint ranks: 1771 existing entries; six modules')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--lean-root', type=Path, required=True)
    emit(parser.parse_args().lean_root)
